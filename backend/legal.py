VERSION = "2026-10-15.1"

_FIELDS = (
    ("entity", "LEGAL_ENTITY", "наименование исполнителя"),
    ("reg", "LEGAL_REG", "регистрационный номер / ИНН"),
    ("address", "LEGAL_ADDRESS", "юридический адрес"),
    ("email", "LEGAL_EMAIL", "адрес для обращений"),
    ("site", "LEGAL_SITE", "адрес сервиса"),
    ("law", "LEGAL_LAW", "применимое право и место рассмотрения споров"),
)


def requisites() -> dict:
    out = {}
    for key, env, what in _FIELDS:
        out[key] = (os.environ.get(env) or "").strip()
    # Телефон в готовность документа не входит, но банк-эквайер требует
    # контакт на сайте — показываем, когда задан.
    out["phone"] = (os.environ.get("LEGAL_PHONE") or "").strip()
    return out


def complete() -> bool:
    r = requisites()
    return all(r[k] for k, _e, _w in _FIELDS)


def missing() -> list:
    r = requisites()
    return [env for key, env, _w in _FIELDS if not r[key]]


def _v(value: str, what: str) -> str:
    # Значение приходит из окружения и попадает в HTML как есть — экранируем:
    # кавычка или «<» в реквизитах не должны ломать разметку документа.
    return html.escape(value) if value else f'<mark class="todo">[указать: {what}]</mark>'


def _brand() -> str:
    return html.escape((os.environ.get("APP_BRAND") or "CAT Translator").strip())


# Получатель текста → (ключ окружения, имя по языкам). OpenAI — всегда:
# без него сервис не переводит вовсе.
