"""Сопоставление термина с текстом: найденная форма — форма ТОГО ЖЕ слова.

`_term_match` ищет термин в любой грамматической форме: режет слово до 85%
букв и разрешает любое кириллическое окончание. Комментарий к порогу говорит,
что 85% выбраны ради хвоста, которым различаются медицинские понятия
(-ит / -оз / -ома), и на шестибуквенном «циклоз» это правда. На одиннадцати
буквах перестало быть правдой:

    стем «туберкулема» = «туберкуле»  ->  ловит «туберкулез» и все его формы

На боевом учебнике одна эта запись сработала ложно 1006 раз, «Туберкулёма
лёгких» — ещё 136, плюс «аллергия -> аллергена», «инфильтрат -> инфильтрации»,
«алкоголизм -> алкоголики». Итого 1185 ложных совпадений на 875 сегментах.
Видно этого не было: вторая половина ошибки гасила первую — `_tgt_has_term`
режет «tuberculoma» до «tuberculo», и «tuberculosis» его удовлетворяет,
поэтому `_gloss_misses` молчал. А в промпт перевода при этом уходил приказ
«use these exact translations: Туберкулема -> Tuberculoma» на сегменты про
туберкулёз.

Правило проверки: у записи и у найденной формы должен найтись ОБЩИЙ стем,
после которого у ОБЕИХ остаётся окончание из закрытого списка словоизменения.
Словообразовательных суффиксов в этом списке нет — ими понятия и различаются.

Замер на боевых данных: снято 1185 ложных совпадений, задето 7 записей
из 152, ни одного верного совпадения не потеряно.

Платных вызовов нет.
"""
import os, sys
os.environ.setdefault("APP_PASSWORD", "test")
os.environ["OPENAI_API_KEY"] = "test-key"
os.environ["AUTHORITY_CORPUS"] = "0"
sys.path.insert(0, "backend")
import main

fail = []


def check(cond, label):
    print(("  OK   " if cond else "  FAIL ") + label)
    if not cond:
        fail.append(label)


# ─────────── 1. Одно слово или разные ───────────
print("=== 1. Форма того же слова против другого слова с общим началом ===")
SAME = [
    ("первичный", "первичного", "прилагательное склоняется"),
    ("первичный", "первичным", "и дальше склоняется"),
    ("туберкулема", "туберкулемы", "существительное склоняется"),
    ("лимфангит", "лимфангита", "найденное начинается с записи целиком"),
    ("туберкулез", "туберкулезного", "производное прилагательное — как было, не трогаем"),
    ("легких", "легкие", "разные окончания одного слова"),
    ("бактериовыделение", "бактериовыделения", "длинное слово склоняется"),
]
DIFF = [
    ("туберкулема", "туберкулеза", "туберкулёма и туберкулёз — разные болезни"),
    ("туберкулема", "туберкулезный", "и прилагательное от другого слова тоже"),
    ("аллергия", "аллергена", "аллергия и аллерген — разные вещи"),
    ("инфильтрат", "инфильтрации", "инфильтрат и инфильтрация — разные вещи"),
    ("алкоголизм", "алкоголики", "болезнь и больные — разные слова"),
    ("дистрофия", "дистрофит", "-ия против -ит"),
    ("пневмония", "пневмонит", "воспаление лёгкого и его же -ит"),
    ("саркома", "саркоидоз", "опухоль и гранулематоз"),
]
for a, b, why in SAME:
    check(main._same_lexeme(a, b) is True, "одно слово: %s / %s - %s" % (a, b, why))
for a, b, why in DIFF:
    check(main._same_lexeme(a, b) is False, "разные: %s / %s - %s" % (a, b, why))

# Известные пределы правила. Записаны тестом, чтобы следующий не считал их
# случайностью и не «чинил» их ослаблением: любое ослабление возвращает
# «туберкулема -> туберкулез».
for a, b, why in [("лимфоузел", "лимфоузлы", "беглая гласная"),
                  ("ребёнок", "ребёнка", "и она же"),
                  ("время", "времени", "разносклоняемое на -мя"),
                  ("гражданин", "граждане", "и на -анин"),
                  ("разрушать", "разрушается", "глагольные формы: список именной")]:
    check(main._same_lexeme(a, b) is False,
          "предел правила: %s / %s - %s" % (a, b, why))
# Весь этот класс на боевом глоссарии - около 4% снятых пар и НИ ОДНОЙ
# приказной записи: цена ошибки тут потерянная подсказка, а не приказ.

check(main._same_lexeme("mycobacterium", "mycobacteria") is True,
      "не кириллица - молчим: список окончаний русский, и для латиницы он "
      "не значит ничего (тот же закон, что у DOMAIN_RULES)")
for bad in ("ма", "за", "оз", "ит", "ома", "ема", "ация", "ник"):
    check(bad not in main._RU_ENDINGS,
          "словообразовательного суффикса «%s» в списке окончаний нет" % bad)


# ─────────── 2. То же самое через сам поиск термина ───────────
print("")
print("=== 2. _term_match: ложные совпадения сняты, верные на месте ===")
CASES = [
    ("Туберкулема", "3. Очаговый туберкулез легких у взрослых", None),
    ("Туберкулёма лёгких", "Очаговый туберкулёз лёгких", None),
    ("аллергия", "введение аллергена под кожу", None),
    ("инфильтрат", "зона инфильтрации в верхней доле", None),
    ("Туберкулема", "Туберкулемы легких на снимке", "Туберкулемы"),
    ("туберкулёз лёгких", "Очаговый туберкулёз лёгких", "туберкулёз лёгких"),
    ("туберкулёз лёгких", "при туберкулёзе лёгких", "туберкулёзе лёгких"),
    ("первичный очаг", "в первичном очаге видны", "первичном очаге"),
    ("лимфангит", "лимфангита не выявлено", "лимфангита"),
    ("инфильтрат", "инфильтраты в лёгких", "инфильтраты"),
    ("Туберкулезный процесс", "признаки туберкулезного процесса", "туберкулезного процесса"),
]
for term, text, want in CASES:
    got = main._term_match(term, text)
    ok = (got or "").lower() == (want or "").lower()
    check(ok, "%-22s в %-34s -> %s" % (repr(term), repr(text), repr(got)))

# Первый стем-хит не гасит поиск. До правки `stem.search` возвращал самое
# левое вхождение, и если оно проверку не проходило, термин объявлялся
# отсутствующим — хотя настоящая форма стояла следующим словом. В учебнике
# фтизиатрии «туберкулёз» и «туберкулёма» стоят в одном абзаце постоянно,
# так что правило гасило бы само себя, и молча: приказ не ушёл бы ни в промпт,
# ни в проверку соответствия глоссарию.
for term, text, want in [
    ("Туберкулема", "Очаговый туберкулез легких. Туберкулемы выявлены.", "Туберкулемы"),
    ("аллергия", "введение аллергена вызывает аллергию", "аллергию"),
    ("инфильтрат", "зона инфильтрации и инфильтраты в доле", "инфильтраты"),
]:
    check((main._term_match(term, text) or "").lower() == want.lower(),
          "ложное вхождение впереди верного не гасит поиск: %s -> %s"
          % (term, want))

# Короткое слово целиком помещается в начало чужого, поэтому послабление
# «найденное начинается с записи целиком» действует только от пяти букв.
for term, text, want in [
    ("тест", "повышен уровень тестостерона", None),
    ("блок", "полная блокада ножки", None),
    ("под", "подключичная вена", None),
    ("рак", "рака лёгкого", "рака"),
    ("нос", "полость носа", "носа"),
]:
    got = main._term_match(term, text)
    check((got or "").lower() == (want or "").lower(),
          "короткая запись: %-6s в %-30s -> %s" % (term, repr(text), repr(got)))
check(main._term_match("туберкулез", "признаки туберкулезного процесса")
      == "туберкулезного",
      "а длинная запись входит в производное как и раньше")

# Мягкие прилагательные среднего рода: без окончания «ее» правило снимало
# законные формы записей, которые в глоссарии есть.
for term, text, want in [("верхний", "верхнее лёгочное поле", "верхнее"),
                         ("средний", "среднее ухо воспалено", "среднее"),
                         ("внутренний", "внутреннее кровотечение", "внутреннее")]:
    check((main._term_match(term, text) or "").lower() == want,
          "средний род мягкого прилагательного находится: %s -> %s" % (term, want))
check(main._same_lexeme("ранний", "раннее") is True,
      "«ранний»/«раннее» правило одобряет, а не находит их стем 85% "
      "(«ранни» против «раннее») - это предел порога, не проверки")

# Точное совпадение проверку не проходит — оно до неё и не доходит.
check(main._term_match("Туберкулема", "Туберкулема верхней доли") == "Туберкулема",
      "точное совпадение возвращается как было: стем-ветка до него не доходит")


# ─────────── 3. Что это меняет выше по течению ───────────
print("")
print("=== 3. Приказ глоссария больше не садится на чужое слово ===")
GL = [{"src": "Туберкулема", "tgt": "Tuberculoma", "tier": "verified",
       "lang": "RU→EN", "domain": "medical"},
      {"src": "туберкулёз лёгких", "tgt": "pulmonary tuberculosis", "tier": "verified",
       "lang": "RU→EN", "domain": "medical"}]
proj = {"id": 1, "title": "P", "src": "RU", "tgt": "EN", "domain": "medical", "segments": []}
main.STATE = {"projects": [proj], "glossary": [dict(g) for g in GL],
              "tm": [], "termQueue": [], "exportHistory": [], "team": []}
main._invalidate_gloss_index()

hits = main._verified_hits("3. Очаговый туберкулёз лёгких у взрослых", proj)
srcs = {h["src"] for h in hits}
check("Туберкулема" not in srcs,
      "сегмент про туберкулёз больше не получает приказ «Туберкулема -> "
      "Tuberculoma» — а получал его на 875 сегментах боевого проекта")
check("туберкулёз лёгких" in srcs,
      "а верную запись получает: правило снимает ложное, не трогая настоящее")

sysmsg = main._translate_system("RU", "EN", hits, None, False, "medical",
                                main._resolve_model(None))
check("Tuberculoma" not in sysmsg,
      "и в промпт перевода этот приказ больше не уходит")
check("pulmonary tuberculosis" in sysmsg, "а верный уходит")


# ─────────── 4. Слепое пятно стороны перевода названо, а не закрыто ───────────
print("")
print("=== 4. Сторона перевода осталась мягкой — намеренно ===")
check(main._tgt_has_term("Focal pulmonary tuberculosis", "Tuberculoma") is True,
      "_tgt_has_term по-прежнему считает «tuberculosis» ответом на "
      "«Tuberculoma»: он режет слово до «tuberculo»")
check(main._tgt_has_term("chest pain", "Tuberculoma") is False,
      "но совсем чужой перевод не проходит")
# Ужесточать её здесь нельзя, и это записано в CLAUDE.md: на боевых данных
# ПОСЛЕ правки оригинала мягкий префикс остаётся единственным основанием
