"""Раскладка страницы PDF: врезки, колонтитулы, подписи — не внутри абзаца.

Четыре дефекта боевой книги (Лазебный, «Пчелиная аптека», перевод RU→UZ):
  1. слово, разрезанное концом страницы («кон-» … «систенцию»), склеивалось
     с врезкой «На заметку» внизу страницы, а продолжение уходило отдельным
     сегментом вместе с рамкой врезки («На заметку ---— хххх систендию»);
  2. колонтитул, распознанный с ошибкой («Апцтоксинотерапия —»), вклеивался
     посреди абзаца, и перенос «расстрой-» / «ства» не склеивался;
  3. подпись эпиграфа «Авиценна» склеивалась со строкой «сокоэффективных …»,
     а «вы-» — с «ди них» («выди них»): текст не терялся, а ПЕРЕСТАВЛЯЛСЯ —
     pypdf отдаёт строки в порядке потока содержимого, а не чтения;
  4. метки рисунка («НК4», «НК1», «Рис. 7») вклеивались в абзац.

PDF собирается руками (`tests/pdf_fixture.py`, без reportlab). Порядок
строк в потоке повторяет боевую книгу: врезка и эпиграф стоят не там,
где их видно на странице.
"""
import io, os, sys, re
os.environ.setdefault("APP_PASSWORD", "test")
sys.path.insert(0, "backend")
import pdftext
import textcount
import importers

fail = []


def check(cond, label):
    print(("  OK   " if cond else "  FAIL ") + label)
    if not cond:
        fail.append(label)


sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pdf_fixture import PDF, HEAD_B2


def paras_of(res):
    return [it[1] for it in res["items"] if it[0] == "p"]


print("=== 1. Геометрия строк достаётся тем же pypdf, строки те же ===")
pages, geoms = textcount._pdf_pages_geom(PDF, [])
from pypdf import PdfReader
plain = [(p.extract_text() or "").splitlines() for p in PdfReader(io.BytesIO(PDF)).pages]
check(pages == plain, "строки с геометрией — буква в букву строки extract_text()")
check(all(g and len(g["lines"]) == len(ls) for g, ls in zip(geoms, pages)), "у каждой страницы есть геометрия на каждую строку")
g0 = geoms[0]
check(any(abs(r[0] - 60) < 1 and abs(r[2] - 320) < 1 and abs(r[3] - 380) < 1 for r in g0["rects"]),
      "нарисованная рамка врезки найдена: %s" % g0["rects"])
check(any(abs(f[0] - 100) < 1 and abs(f[3] - 520) < 1 for f in geoms[3]["figs"]), "рисунок найден: %s" % geoms[3]["figs"])
k = pages[4].index("Авиценна")
check(abs(geoms[4]["lines"][k][0] - 300) < 1 and abs(geoms[4]["lines"][k][1] - 350) < 1,
      "место строки — x и базовая линия: %s" % geoms[4]["lines"][k])
check(pages[4].index("сокоэффективных лечебно-профилактических средств. Сре-") > pages[4].index("Авиценна"),
      "в потоке строка «сокоэффективных» стоит после подписи эпиграфа — как в боевой книге")
par = textcount._pdf_extract_parallel(PDF, len(pages), 2)
check(par is not None and par[0] == pages and [bool(g) for g in par[1]] == [True] * len(pages),
      "дочерние процессы отдают те же строки и геометрию")

print("=== 2. С геометрией: все четыре дефекта ===")
res = pdftext.clean(pages, geom=geoms)
P = paras_of(res)
print("   report:", res["report"])
for p in P:
    print("     |", p[:110])
check(any("ниже 20 °С консистенцию, массовую долю воска" in p for p in P),
      "1: «кон-» склеено с «систенцию» через врезку, номер и колонтитул")
check("На заметку" in P, "1: заголовок врезки — свой абзац")
check(any(p.startswith("В продаже на рынках, как правило, покупателю предлагают") for p in P),
      "1: текст врезки — свой абзац, мягкие переносы внутри склеены")
check(not any("хххх" in p or "---" in p for p in P), "1: рамка врезки («---— хххх») снята как мусор")
check(not any("кон- В продаже" in p or "На заметку систенцию" in p for p in P), "1: врезка не в абзаце, продолжение не во врезке")
check(any("желудочно-кишечные расстройства, частая тошнота" in p for p in P),
      "2: «расстрой-» склеено с «ства» через колонтитул с ошибкой, метки и подпись рисунка")
check(not any(HEAD_B2 in p or "токсинотерапия" in p or "Лекарство из" in p for p in P),
      "2: колонтитулы (и с ошибкой распознавания) сняты: %s" % res["heads"])
check({"НК4", "НК1", "Рис. 7"} <= set(P), "4: метки и подпись рисунка — отдельные абзацы")
check(not any(re.search(r"НК\d.{3,}|.{3,}НК\d", p) for p in P), "4: метки не вклеены в абзацы")
check("Авиценна" in P, "3: подпись эпиграфа — свой абзац")
check(any(p.startswith("Все, что нас окружает, — в определенной степени яд") and p.endswith("ядом или нет.") for p in P),
      "3: эпиграф — свой абзац")
check("Пчелиный яд" in P, "3: заголовок главы — свой абзац")
check(any("взято немало высокоэффективных лечебно-профилактических средств. Среди них определенное место" in p for p in P),
      "3: текст не потерян и не переставлен: «вы-» + «сокоэффективных» + «Сре-» + «ди них»")
order = [next(i for i, p in enumerate(P) if p.startswith(s)) for s in
         ("Хранить прополис", "Пчелиный яд", "Все, что нас", "Авиценна", "Из сокровищницы")]
check(order == sorted(order), "3: порядок чтения: текст → заголовок → эпиграф → подпись → абзац")
check(not any(re.fullmatch(r"\d+", p) for p in P) and res["report"].get("pageNumbers") == 8, "номера страниц сняты")

print("=== 3. Без геометрии (прежний вход — списки строк) ===")
res2 = pdftext.clean(pages)
P2 = paras_of(res2)
check(any("ниже 20 °С консистенцию, массовую долю воска" in p for p in P2),
      "1 без геометрии: хвост страницы после «кон-», начатый заглавной, — врезка")
check(any(p.startswith("В продаже на рынках") for p in P2) and not any("хххх" in p for p in P2),
      "1 без геометрии: врезка — свой абзац, рамка снята")
check(any("желудочно-кишечные расстройства, частая тошнота" in p for p in P2),
      "2 без геометрии: короткие метки в начале страницы пропущены до продолжения слова")
check(not any("Апцтоксинотерапия" in p or "Лекарство из улъя" in p for p in P2),
      "2 без геометрии: колонтитул с ошибкой распознавания узнан нечётко")
# Без геометрии порядок потока остаётся («вы-» склеится с «ди них» — это
# предел строк без места), но буквы те же: ничего не потеряно и не добавлено.
from collections import Counter
letters = lambda ps: Counter(c for p in ps for c in p if c.isalpha())
check(letters(P) == letters(P2), "с геометрией и без — те же буквы (ничего не потеряно)")

print("=== 4. Частные правила ===")
for s in ("---— хххх", "————", "= = = = =", "- - - - -", "V-----------------------", "_____ xxxx"):
    check(pdftext._is_border_line(s), "рамка: %r" % s)
for s in ("— 23 —", "— Да, — сказал он.", "Глава 1 ———", "НК-21", "COVID-19", "т. е.", "---- мед"):
    check(not pdftext._is_border_line(s), "не рамка: %r" % s)
check(pdftext._in_frame("Апцтоксинотерапия —", {"Апитоксинотерапия —"})
      and not pdftext._in_frame("АПИТОКСИНОТЕРАПИЯ", {"Апитоксинотерапия"})
      and not pdftext._in_frame("НК 21", {"НК 12"}),
      "колонтитул узнаётся с ошибкой распознавания, но не КАПСОМ и не короткий")
# Врезка без рамки: две строки подряд с отступом и своим правым краем.
recs = [{"t": "Обычный текст абзаца идёт от поля до поля и дальше", "x0": 40, "x1": 340, "y": 500, "s": 10},
        {"t": "и продолжается здесь ровно до правого поля страницы", "x0": 40, "x1": 340, "y": 488, "s": 10},
        {"t": "третья строка тоже полная, как положено тексту", "x0": 40, "x1": 340, "y": 476, "s": 10},
        {"t": "и четвёртая строка абзаца кончается точкой.", "x0": 40, "x1": 300, "y": 464, "s": 10},
        {"t": "ВК 28", "x0": 56, "x1": 80, "y": 440, "s": 10},
        {"t": "Расположена кзади от сустава II пальца руки, на кости.", "x0": 56, "x1": 345, "y": 428, "s": 10},
        {"t": "Показания к возможному использованию:", "x0": 56, "x1": 250, "y": 416, "s": 10},
        {"t": "одышка; невралгия тройничного нерва, боль в глазах.", "x0": 40, "x1": 330, "y": 404, "s": 10}]
st = pdftext._page_stats(recs)
n = [0]
roles = pdftext._geo_roles(recs, st, {"box": [0, 0, 400, 600]}, lambda: n.__setitem__(0, n[0] + 1) or n[0])
check(all(r[0] == "f" for r in roles), "однострочные абзацы с отступом («ВК 28», «Расположена…») — не врезка: %s" % roles)

print("=== 4a. Дробь, степень и химический индекс — на своём месте ===")
# Типограф ставит числитель дроби, степень и индекс выше или ниже базовой
# линии, и pypdf при сдвиге примерно от 0.65 em РВЁТ на этом месте строку.
# До правки порядок чтения (сверху вниз) уносил надстрочник прочь:
# «и пить по ¹/₃ стакана» превращалось в «1 и пить по /3 стакана».
# Правило одно на все предметы: «m²», «H₂O», «¹⁴C», «x₁» ломаются так же.
from pdf_fixture import make_pdf
from pdfpages_worker import page_lines
from pypdf import PdfReader as _RD
_body = [("t", 50, 560 - 14 * i, 12,
          "Обычная строка книги номер %d про лечение прополисом и мёдом." % i) for i in range(6)]
_page = _body + [
    ("t", 50, 460, 12, "и пить по "),
    ("t", 110, 469, 8, "1"),
    ("t", 116, 460, 12, "/"),
    ("t", 122, 455, 8, "3"),
    ("t", 130, 460, 12, " стакана в день за 20-30 минут до еды каждый раз."),
    ("t", 50, 440, 12, "Формула воды H"),
    ("t", 132, 436, 8, "2"),
    ("t", 138, 440, 12, "O известна всем, а площадь в м"),
    ("t", 320, 449, 8, "2"),
    ("t", 326, 440, 12, " измеряют так."),
]
_lines, _geom = page_lines(_RD(io.BytesIO(make_pdf([_page]))).pages[0])
check("1" in _lines and "и пить по " in _lines,
      "pypdf и правда разрывает строку на надстрочнике: %s" % _lines[6:9])
_res = pdftext.clean([_lines], geom=[_geom])
_pp = paras_of(_res)
check(any("по 1/3 стакана" in x for x in _pp), "дробь собрана обратно: %s" % _pp[6:])
check(not any(x.startswith("1 ") for x in _pp), "числитель не уехал в начало абзаца")
check(any("H2O" in x and "в м2 измеряют" in x for x in _pp),
      "химический индекс и степень — тоже: %s" % _pp[-1:])
check(_res["report"].get("scripts") == 2, "и всё снятое названо числом: %s" % _res["report"].get("scripts"))

# Обрывок рисунка у края страницы («Ш», «ж») приклеивать НЕЛЬЗЯ: он тоже
# короткий и стоит рядом с чужой базовой линией. Различает их цифра.
check(pdftext._script_piece({"t": "1"}) and pdftext._script_piece({"t": "14C"}),
      "кандидат на приклейку — кусок с цифрой")
check(not pdftext._script_piece({"t": "Ш"}) and not pdftext._script_piece({"t": "ж т"}),
      "обрывок рисунка без цифр кандидатом не считается")

print("=== 4b. Повреждённый знак математики не снимается как орнамент ===")
# Боевая книга, стр. 161: распознаватель прочёл надстрочную «1» как «*»,
# и токен «*/» терялся целиком — оставалось «по / стакана».
from collections import Counter as _C
_line = "на стакан настоя и пить его теплым по */ стакана 3-4 раза в"
check(pdftext._clean_line(_line, _C()) == _line, "«*/» остаётся: удалённое повреждение неотличимо от целого текста")
check(pdftext._clean_line("мусор <308> и |1 и #12", _C()) == "мусор 308 и 1 и 12",
      "а обычный мусор распознавания чистится, как чистился")
check(pdftext._clean_line("* * *", _C()) is None, "орнамент «* * *» по-прежнему снимается целиком")

print("=== 5. Импорт PDF целиком: абзацы .docx ===")
docx, kind, note, n_img = importers.pdf_to_docx(PDF)
from docx import Document
dp = [p.text for p in Document(io.BytesIO(docx)).paragraphs if p.text.strip()]
check(kind == "pdf" and dp == P, "в .docx ровно абзацы чистки с геометрией")
check("мусора" in note, "рамка врезки названа в отчёте как снятый мусор: %s" % note)

print()
if fail:
    print("FAILED: %d" % len(fail))
    for x in fail:
        print(" -", x)
    sys.exit(1)
print("ALL OK")
