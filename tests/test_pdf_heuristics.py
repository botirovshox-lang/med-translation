print("=== D. Колонтитулы: тысяча страниц со своей строкой в полосе ===")
import random
random.seed(7)
W = "пчела мед воск яд прополис лечение сустав кожа сердце точка курс сеанс боль сон кровь".split()


def book(distinct):
    pages = []
    for p in range(1000):
        head = ("Раздел %d: %s" % (p, " ".join(random.choice(W) for _ in range(4)))
                if distinct else "Колонтитул книги")
        pages.append(page([(head, 40, 570, 11, 300)] + body_lines(12, y0=540)
                          + [(str(p + 1), 200, 40, 10, 212)]))
    return [x[0] for x in pages], [x[1] for x in pages]


ls, gs = book(False)
t = time.time(); pdftext.clean(ls, geom=gs); same = time.time() - t
ls, gs = book(True)
t = time.time(); pdftext.clean(ls, geom=gs); distinct = time.time() - t
check(distinct < 3 * same + 2, "своя строка в полосе на каждой странице: %.1f с против %.1f с с одним колонтитулом"
      % (distinct, same))

