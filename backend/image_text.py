_SANS = ROOT.parent / "frontend" / "vendor" / "fonts" / "sub"


_COVER: dict = {}


def _font_covers(path: str, text: str) -> bool:
    """Знает ли файл шрифта все буквы перевода (fontTools, кэш по пути)."""
    if path not in _COVER:
        try:
            from fontTools.ttLib import TTFont
            _COVER[path] = set(TTFont(path, lazy=True).getBestCmap() or {})
        except Exception:
            _COVER[path] = None
    have = _COVER[path]
    if have is None:
        return True
    return all(ord(ch) in have for ch in text if not ch.isspace())


# Шрифты письменностей, которых нет в Noto Sans и DejaVu. Иероглифы — в порядке
# «китайский, японский, корейский»: общие иероглифы знают все три, а кана
# и хангыль — только свой, поэтому первый, кто знает ВСЕ буквы, и есть нужный.
_SCRIPT_FONTS = ("NotoSansSC-Regular.otf", "NotoSansJP-Regular.otf", "NotoSansKR-Regular.otf",
                 "NotoSansArabic", "NotoSansHebrew", "NotoSansArmenian", "NotoSansGeorgian",
                 "NotoSansDevanagari", "NotoSansBengali", "NotoSansGujarati", "NotoSansGurmukhi",
                 "NotoSansTamil", "NotoSansTelugu", "NotoSansThai", "NotoSansKhmer",
                 "NotoSansMyanmar", "NotoSansEthiopic")


def _pf():
    try:
        from backend import print_fonts as pf
    except ImportError:
        import print_fonts as pf
    return pf


def _paint_font(bold: bool, text: str = "", fam: str = "") -> Optional[str]:
    """Шрифт перевода надписи — первый, что знает ВСЕ его буквы.

    `fam == "hand"` (страница от руки, `main._hand_image`) — сперва
    рукописные файлы общего списка (`print_fonts`, Ф1): прежде путь картинок
    печатал конспект гротеском, хотя путь PDF уже брал рукописный шрифт.
    Дальше — рубленый: Noto Sans (как у выгрузки PDF), DejaVu, затем шрифты
    письменностей из `frontend/vendor/fonts/sub`. 12.10.2026 китайский перевод
    таблички рисовался DejaVu — квадратиками вместо каждого иероглифа, а отчёт
    говорил «написано»."""
    for p in _pf().family_files(fam, bold):
        if _font_covers(p, text):
            return p
    p = _SANS / ("NotoSans-Bold.ttf" if bold else "NotoSans-Regular.ttf")
    if p.exists() and _font_covers(str(p), text):
        return str(p)
    d = font_path(bold)
    if d and _font_covers(d, text):
        return d
    for name in _SCRIPT_FONTS:
        cands = [name] if "." in name else [name + ("-Bold.ttf" if bold else "-Regular.ttf"),
                                            name + "-Regular.ttf"]
        for c in cands:
            f = _SANS / c
            if f.exists() and _font_covers(str(f), text):
                return str(f)
    return d


def _paint_measure(arr, pbox, it: dict, k: int, draw) -> Optional[dict]:
    """Замер надписи по пикселям и стирание (`text_paint`): цвет, кегль,
    жирность, угол и дуга — как у оригинала; у абзаца с рамками строк —
    базы, шаг и отступ (Ф1). None — нечем или букв не нашлось (вызывающий
    идёт прежней дорогой)."""
    tp = _tp()
    if tp is None:
        return None
    x0, y0, x1, y1 = pbox
    rgb = _np.ascontiguousarray(_visible(arr[y0:y1, x0:x1])[..., :3].astype(_np.uint8))
    rows = max(1, int(it.get("rows") or 1))
    bx = it.get("box") or [x0, y0, x1, y1]
    inner = (bx[0] - x0, bx[1] - y0, bx[2] - x0, bx[3] - y0)
    try:
        m = tp.measure(rgb, it.get("src") or "", rows, float(it.get("lineH") or 0), inner=inner)
        if not m.get("found"):
            return None
        erased, alpha = tp.erase(rgb, m)
    except Exception:
        return None
    if len(m["bands"]) > rows + 1:
        m["bands"] = []
    fam = it.get("fam") or ""
    text = it.get("text") or ""
    lbs = it.get("lineBoxes") or []
    if fam != "hand" and len(lbs) >= 2 and not m["angle"] and not m.get("arc"):
        # Х1: машинопись — машинописным шрифтом (шаг знака постоянный).
        sc = tp.mono_score(m["mask"], [[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0]
                                       for lb in lbs], len(" ".join((it.get("src") or "").split())))
        if sc is not None and sc >= tp.MONO_COH:
            fam = "type"
    if fam != "hand" and not m["angle"] and not m.get("arc"):
        # Х9: засечки — по буквам; одна строка без рамок — вся вырезка.
        loc = ([[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0] for lb in lbs]
               if lbs else [[0, 0, rgb.shape[1], rgb.shape[0]]] if rows == 1 else [])
        fam = tp.serif_fam(m["mask"], loc, fam, "")
        if m["bold"] and not tp.bold_by_area(m["mask"], loc, " ".join((it.get("src") or "").split()),
                                             float(m["em"]), _paint_font(False, text, fam) or "",
                                             _paint_font(True, text, fam) or ""):
            m["bold"] = False               # Х11: жирный — от размытия
    if fam == "serif" and (it.get("era") == "old" or _pf().pre_reform(it.get("src") or "")):
        fam = "old"                         # Х10: дореформенная печать
    fpath = _paint_font(m["bold"], text, fam)
    if not fpath:
        return None
    cache: dict = {}

    def font_at(s, path=fpath):
        s = max(4, int(round(s)))
        key = (path, s)
        if key not in cache:
            cache[key] = ImageFont.truetype(path, s)
        return cache[key]

    geo = None
    if not m["angle"] and not m.get("arc") and rows >= 2 and len(lbs) == rows:
        loc = [[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0] for lb in lbs]
        g = tp.line_geometry(loc, m["mask"], m["em"])
        if g and g["regular"]:
            geo = g
    em = m["em"] * k
    src = " ".join((it.get("src") or "").split())
    if fam != "hand" and not m["angle"] and not m.get("arc"):
        # Х10: кегль по строчным оригинала и нашего шрифта.
        xl = ([[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0] for lb in lbs]
              if lbs else [[0, 0, m["mask"].shape[1], m["mask"].shape[0]]] if rows == 1 else [])
        em = tp.em_by_xheight(em, tp.x_height(m["mask"], xl) * k, fpath, src)
    h0 = 1.0
    if src and not m["angle"] and not m.get("arc") and (m["bands"] or geo):
        inkw = 0.0
        if geo:
            # Ширина краски — по рамкам строк: полосы маски у почерка слиты
            # и раздроблены (Ф1), и ширина по ним теряла целые строки.
            H_, W_ = m["mask"].shape[:2]
            for lb in loc:
                a, b = max(0, int(lb[1])), min(H_, int(math.ceil(lb[3])))
                c, d = max(0, int(lb[0])), min(W_, int(math.ceil(lb[2])))
                if b > a and d > c:
                    cols = _np.nonzero(m["mask"][a:b, c:d].any(axis=0))[0]
                    if len(cols):
                        inkw += (cols[-1] - cols[0] + 1) * k
        else:
            for a, b in m["bands"]:
                cols = _np.nonzero(m["mask"][a:b + 1].any(axis=0))[0]
                if len(cols):
                    inkw += (cols[-1] - cols[0] + 1) * k
        # Исходный текст меряется шрифтом, который знает ЕГО буквы: иначе
        # отношение ширины — про квадратики, а не про почерк.
        mpath = fpath if _font_covers(fpath, src) else (_paint_font(m["bold"], src) or fpath)
        ours = draw.textlength(src, font=font_at(em, mpath))
        # Ширине краски верим только по рамкам строк: полосы маски у почерка
        # слиты и раздроблены, и кегль по ним выходил вдвое мельче.
        em, h0 = tp.calibrate(em, inkw, ours, hand=(fam == "hand" and geo is not None), hmin=0.74)
    # Толщина штриха (Ф7) — у почерка и у машинописи: шрифт тоньше ручки
    # и удара литеры.
    # Ф7 — только у рукописи (перо); машинопись — плотностью набора (Х13):
    # штрих по маске размытие раздувает, и перевод машинописи выходил
    # жирнее оригинала (плотность 0.449 против 0.31).
    stem = tp._stem(m["mask"]) * k if fam == "hand" else 0.0
    stem_mid = 0.0
    dens = 0.0
    if fam != "hand" and not m["angle"] and not m.get("arc") and lbs:
        # Х12: вес — по середине тона между бумагой и краской.
        stem_mid = tp.stem_mid(rgb, [[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0] for lb in lbs],
                               m.get("bg") or (255, 255, 255), m["ink"]) * k
        dens = tp.band_density(rgb, [[lb[0] - x0, lb[1] - y0, lb[2] - x0, lb[3] - y0] for lb in lbs],
                               m.get("bg") or (255, 255, 255), m["ink"])
        ci = tp.core_ink(rgb, m["mask"], m.get("bg") or (255, 255, 255), m["ink"], stem_mid / k)
        if ci is not None:
            m["ink"] = ci                   # Х13: цвет — по оси штриха
    # Х2: выключка — по краям строк оригинала, если они её говорят.
    align = (geo or {}).get("align") or it.get("align") or "left"
    if fam == "hand" and align == "justify":
        align = "left"                      # почерк по ширине не выключается
    return {"m": m, "erased": erased, "alpha": alpha, "fpath": fpath, "font_at": font_at,
            "em": em, "h0": h0, "geo": geo, "k": k, "pbox": pbox, "it": it, "fam": fam,
            "align": align,
            "ink": m["ink"], "stem": stem, "stemMid": stem_mid, "dens": dens,
            "handFallback": fam == "hand" and fpath not in _pf().hand_font_files()}


def _paint_layout(pm: dict, draw, em: Optional[float] = None, step: Optional[float] = None,
                  extra: int = 0, fixed: bool = False) -> Optional[dict]:
    """Раскладка перевода по замеру `pm`. None — не влезло (дуга, наклон,
    блок без рамок строк): вызывающий идёт прежней дорогой."""
    tp = _tp()
    m, k, it = pm["m"], pm["k"], pm["it"]
    x0, y0, x1, y1 = pm["pbox"]
    font_at, h0 = pm["font_at"], pm["h0"]
    em = em or pm["em"]
    text = it.get("text") or ""

    def mw(t, s):
        return draw.textlength(t, font=font_at(s)) * h0
    w = (x1 - x0) * k
    parts = None
    over = False
    geo = pm.get("geo")
    if m.get("arc"):
        arc = m["arc"]
        rb = max(1.0, arc["r"] - arc["up"] * 0.36 * m["em"]) * k
        width = abs(arc["t1"] - arc["t0"]) * rb * 1.25 + em
        one = " ".join(text.split())
        size = em
        while size > 0.45 * em and mw(one, size) > width:
            size *= 0.96
        if mw(one, size) > width * 1.05:
            return None                 # длиннее дуги и на полу — плашкой, прежней дорогой
        lines, step_ = [one], size
    elif m["angle"]:
        width = math.hypot(x1 - x0, y1 - y0) * k * 0.92
        one = " ".join(text.split())
        size = em
        while size > 0.45 * em and mw(one, size) > width:
            size *= 0.96
        # Наклонная надпись пишется ОДНОЙ строкой. Не влезла и на полу —
        # строка вылезла бы за рамку, а то и за край картинки (замер на
        # китайском переводе длинного блока) — значит плашкой.
        if mw(one, size) > width * 1.05:
            return None
        lines, step_ = [one], size
    elif geo:
        # Абзац с ровным ритмом строк (Ф1–Ф3): строки перевода стоят на
        # базовых линиях оригинала тем же шагом, первая — с отступом
        # оригинала; длинный перевод идёт в свободные строки ниже, потом
        # мельче буквами при том же шаге, и только потом теснее.
        if geo.get("heads") and "\n" not in text:
            # Х3: абзацы внутри блока — разрыв на конце предложения.
            text = tp.para_breaks(text, geo["shares"])
        rtl = _rtl(text)
        align = pm.get("align") or "left"
        align = _start_align(align, text)
        left, right = geo["left"] * k, geo["right"] * k
        # Отступ — у начала строки: у письма справа налево — справа (Х4).
        indent = geo["indent"] * k if (align in ("left", "justify") or (rtl and align == "right")) else 0.0
        st0 = (step or geo["pitch"]) * k
        size, step_, lines, over = tp.fit_rhythm(
            text, right - left, em, st0, geo["rows"], extra, mw,
            lambda wd, room, sz: _split_cjk(lambda t: mw(t, sz), wd, room), indent, fixed)
        if not lines or (over and fixed):
            return None
        if over:
            # Не влезло и тесно — прежняя дорога (строки в рамке абзаца или
            # плашка), а не строки поверх соседнего абзаца.
            return _paint_layout(dict(pm, geo=None), draw)
        base0 = geo["base0"] * k
        heads = tp.rhythm_heads(text, right - left, size, mw,
                                lambda wd, room, sz: _split_cjk(lambda t: mw(t, sz), wd, room), indent)
        parts = [{"bases": [base0 + i * step_ for i in range(len(lines))], "x0": left,
                  "x1": right, "indent": indent, "lines": lines, "size": size,
                  "step": step_, "font": font_at(size), "heads": heads, "rtl": rtl,
                  "justify": align == "justify"}]
    else:
        bands = m["bands"]
        areas = m.get("areas") or []
        if len(bands) >= 2 and len(areas) > 1:
            weights = [float(m["mask"][bands[a0][0]:bands[a1][1] + 1].sum()) for a0, a1 in areas]
            chunks = tp.split_text(text, weights)
            spans = [(bands[a0][0] * k, (bands[a1][1] + 1) * k, a1 - a0 + 1) for a0, a1 in areas]
        else:
            chunks = [text]
            spans = [(bands[0][0] * k if bands else 0,
                      (bands[-1][1] + 1) * k if bands else (y1 - y0) * k, max(1, len(bands)))]
        parts = []
        for (top, bot, rows_k), chunk in zip(spans, chunks):
            height = max(bot - top, em)
            pitch = max(m["pitch"] * k, em * 1.05)
            # Строк не больше, чем вместит место ПО ТОЙ ЖЕ мерке, которой
            # раскладку проверяют ниже (Ф1): лишние полосы маски (обрывки
            # выносных) разрешали `fit_lines` раскладку, которую проверка
            # тут же отвергала, и блок уходил на плашку.
            cap = int((height + 0.6 * em - 0.95 * em) // max(pitch, 1e-6)) + 1
            rows_k = max(1, min(rows_k, cap))
            size, step_, lines = tp.fit_lines(chunk, w, height + 0.3 * em, em, pitch, mw,
                                              lambda wd, room, sz: _split_cjk(lambda t: mw(t, sz), wd, room),
                                              0.45, rows_k)
            if lines and (len(lines) - 1) * step_ + 0.95 * size > height + 0.6 * em:
                return None             # не влезло и мельче — плашкой, прежней дорогой
            parts.append({"top": top, "bot": bot, "lines": lines, "size": size, "step": step_,
                          "font": font_at(size)})
        size = min(p_["size"] for p_ in parts)
        step_ = parts[0]["step"]
        lines = [ln for p_ in parts for ln in p_["lines"]]
    if size < IMG_FONT_MIN_PX * k * 0.6:
        return None
    stroke = 0
    stroke_f = 0.0
    if pm.get("stem") and not m.get("arc") and not m["angle"]:
        stroke = tp.stroke_for(pm["stem"], tp.font_stem(pm["fpath"]), size)
    elif ((pm.get("stemMid") or 0) >= tp.WEIGHT_MIN_PX * k and pm.get("dens") and lines
          and not m.get("arc") and not m["angle"]):
        # Х13: обводка — до ПЛОТНОСТИ набора оригинала (доля краски в полосе
        # строчных): толщина штриха в точках у перевода, сжатого по ширине,
        # читается жирнее — краски на узкой букве больше. Пробная строка
        # перевода рисуется тем же шрифтом, кеглем, сжатием и краской.
        bg_ = tuple(int(v) for v in (m.get("bg") or (255, 255, 255)))
        ink_ = tuple(int(v) for v in (pm.get("ink") or m["ink"]))
        sample = max(lines, key=len)
        fpth = getattr(font_at(size), "path", None) or pm["fpath"]

        def dens_at(sf):
            return tp.sample_density(fpth, sample, size, h0, ink_, bg_, sf)
        stroke_f = tp.weight_by_density(pm["dens"], dens_at, tp.STROKE_MAX * size)
    return {"pbox": pm["pbox"], "stroke": stroke, "strokeF": stroke_f, "erased": pm["erased"],
            "dash": pm.get("fam") == "hand" and _short_hyphen(pm["fpath"]),
            "alpha": pm["alpha"], "m": m, "lines": lines, "size": size, "step": step_, "h0": h0, "font": font_at(size),
            "k": k, "align": _start_align(pm.get("align") or it.get("align"), text), "parts": parts,
            "ink": pm.get("ink") or m["ink"], "over": bool(over)}


def _paint_plan(arr, pbox, it: dict, k: int, draw) -> Optional[dict]:
    """Замер и раскладка одним вызовом (блок сам по себе, без страницы)."""
    pm = _paint_measure(arr, pbox, it, k, draw)
    return None if pm is None else _paint_layout(pm, draw)


# Ф3. Сколько свободных строк ниже абзаца можно взять под длинный перевод:
# той же линовкой, пока строка не задевает чужой блок (с прежним зазором:
# была пустая строка между абзацами — она остаётся), не выходит за низ
# картинки и не ложится на краску, которой разбор не прочёл (рисунок,
# непрочитанный текст). Не больше `IMG_EXTRA_ROWS` и не больше строк самого
# абзаца.
IMG_EXTRA_ROWS = int(os.environ.get("IMG_EXTRA_ROWS", "6"))


def _free_rows(pm: dict, others: list, arr, w: int, h: int, step: Optional[float] = None) -> int:
    """`step` — шаг, которым строки будут НАПЕЧАТАНЫ (общий шаг класса):
    проверять место надо там, куда они лягут."""
    geo = pm.get("geo")
    if not geo or IMG_EXTRA_ROWS <= 0:
        return 0
    tp = _tp()
    k = pm["k"]
    x0, y0 = pm["pbox"][0], pm["pbox"][1]
    em = pm["em"] / k
    p = step or geo["pitch"]
    last = y0 + geo["base0"] + (geo["rows"] - 1) * p
    L, R = x0 + geo["left"], x0 + geo["right"]
    top, bottom = y0 + geo["top"], y0 + geo["bottom"]
    n = 0
    for j in range(1, min(IMG_EXTRA_ROWS, geo["rows"]) + 1):
        b = last + j * p
        t_, b_ = b - 0.85 * em, b + 0.35 * em
        if b_ > h - 0.25 * p:
            break
        blocked = False
        for o in others:
            if o[2] <= L or o[0] >= R or o[3] <= top:
                continue
            keep = p if (o[1] - bottom) >= p else 0.25 * p
            if b_ + keep > o[1]:
                blocked = True
                break
        if blocked:
            break
        reg = arr[max(0, int(t_)):min(h, int(math.ceil(b_))), max(0, int(L)):min(w, int(math.ceil(R)))]
        if tp is None or tp.has_letters(_np.ascontiguousarray(_visible(reg)[..., :3].astype(_np.uint8)), em):
            break
        n += 1
    return n


def _page_even(pms: list, draw, arr, w: int, h: int, others_of) -> dict:
    """Ф4: один кегль, шаг и цвет на класс абзацев страницы. {номер: план}."""
    tp = _tp()
    idx = [i for i, pm in enumerate(pms) if pm is not None and pm.get("geo")]
    out: dict = {}
    if tp is None or len(idx) < 2:
        return out
    ents = [{"em": pms[i]["em"], "fam": pms[i]["fam"]} for i in idx]
    for cls in tp.even_classes(ents):
        mem = [idx[c] for c in cls]
        em_c = sorted(pms[i]["em"] for i in mem)[len(mem) // 2]
        st_c = tp.even_step([pms[i]["geo"]["pitch"] for i in mem])
        h0s = sorted(pms[i]["h0"] for i in mem)
        h0_c = h0s[len(h0s) // 2]
        stems = sorted(pms[i].get("stem") or 0.0 for i in mem)
        stem_c = stems[len(stems) // 2]
        fits = {}
        own = {i: (pms[i]["h0"], pms[i].get("stem")) for i in mem}

        def back(ids):
            for j_ in ids:
                pms[j_]["h0"], pms[j_]["stem"] = own[j_]
        for i in mem:
            pms[i]["h0"] = h0_c
            if stem_c:
                pms[i]["stem"] = stem_c
            pms[i]["_extra"] = _free_rows(pms[i], others_of(i), arr, w, h, step=st_c)
            pl = _paint_layout(pms[i], draw, em=em_c, step=st_c, extra=pms[i]["_extra"])
            if pl is None or pl["over"] or not pl.get("parts") or not pl["parts"][0].get("bases") \
                    or pl["size"] < tp.FIT_FLOOR * em_c - 1e-6:
                back([i])                   # не держит класс — раскладывается сам, своим
                continue
            fits[i] = pl["size"]
        if len(fits) < tp.EVEN_MIN:
            back(fits)
            continue
        size_c = min(fits.values())
        inks = [pms[i]["ink"] for i in fits]
        ink_c = tuple(int(sorted(c[j] for c in inks)[len(inks) // 2]) for j in range(3))
        for i in fits:
            pms[i]["ink"] = ink_c
            pl = _paint_layout(pms[i], draw, em=size_c, step=st_c, extra=pms[i]["_extra"],
                               fixed=True)
            if pl is not None:
                out[i] = pl
    return out


def _rtl(text: str) -> bool:
    """Письмо справа налево берёт верх над буквами слева направо."""
    r = l = 0
    for ch in text or "":
        o = ord(ch)
        if 0x0590 <= o <= 0x08FF or 0xFB1D <= o <= 0xFEFC:
            r += 1
        elif ch.isalpha():
            l += 1
    return r > l


def _start_align(align, text) -> str:
    """«Влево» — это НАЧАЛО строки. У перевода справа налево (арабский,
    иврит, фарси) начало строки справа: 13.10.2026 арабский абзац Чехова
    встал рваным правым краем от левого поля. Центр и «вправо» (колонка
    чисел) остаются как были."""
    align = align or "left"
    return "right" if align == "left" and _rtl(text) else align


def _put(big, im, pos) -> None:
    """Слой на картинку; за край — обрезается (старый Pillow на отрицательную
    точку у `alpha_composite` отвечает ошибкой)."""
    x, y = int(pos[0]), int(pos[1])
    if x < 0 or y < 0:
        im = im.crop((max(0, -x), max(0, -y), im.size[0], im.size[1]))
        x, y = max(0, x), max(0, y)
    if im.size[0] <= 0 or im.size[1] <= 0:
        return
    if big.mode == "RGBA":
        big.alpha_composite(im, (x, y))
    else:
        big.paste(im, (x, y), im)


def _paint_put(big, p: dict) -> None:
    """Текст надписи — слоями: строка рисуется на прозрачный слой, сжимается
    по ширине (`h0`), поворачивается и кладётся на место."""
    m, k = p["m"], p["k"]
    x0, y0, x1, y1 = p["pbox"]
    font, size, step, h0 = p["font"], p["size"], p["step"], p["h0"]
    ink = tuple(int(v) for v in (p.get("ink") or m["ink"])) + (255,)
    sw = int(p.get("stroke") or 0)

    def layer(txt, f_=None, s_=None):
        f_ = f_ or font
        s_ = s_ or size
        if p.get("dash"):
            # Х7: дефис рукописного шрифта слишком мал — тире (только печать).
            txt = txt.replace("-", "\u2013")
        sf = float(p.get("strokeF") or 0.0)
        if sf > 0 and not sw and getattr(f_, "path", None):
            # Х12: дробная обводка — слой крупнее в SUP раз, затем вниз.
            SUP = 4
            fb = ImageFont.truetype(f_.path, max(4, int(round(f_.size * SUP))))
            swb = max(1, int(round(sf * SUP)))
            bb = fb.getbbox(txt, stroke_width=swb)
            wb = max(SUP, bb[2] - min(0, bb[0]) + 2 * SUP + swb)
            hb = max(SUP, int(s_ * 1.4 * SUP) + 2 * swb)
            imb = Image.new("RGBA", (wb, hb), (0, 0, 0, 0))
            ImageDraw.Draw(imb).text((SUP + swb, swb), txt, font=fb, fill=ink, stroke_width=swb,
                                     stroke_fill=ink)
            wl, hl = max(1, int(round(wb / SUP))), max(1, int(round(hb / SUP)))
            return imb.resize((max(1, int(wl * h0)), hl), Image.LANCZOS)
        bb = f_.getbbox(txt, stroke_width=sw)
        wl, hl = max(1, bb[2] - min(0, bb[0]) + 2 + sw), max(1, int(s_ * 1.4) + 2 * sw)
        im = Image.new("RGBA", (wl, hl), (0, 0, 0, 0))
        if sw:
            ImageDraw.Draw(im).text((1 + sw, sw), txt, font=f_, fill=ink, stroke_width=sw,
                                    stroke_fill=ink)
        else:
            ImageDraw.Draw(im).text((1, 0), txt, font=f_, fill=ink)
        if h0 < 0.999:
            im = im.resize((max(1, int(wl * h0)), hl), Image.LANCZOS)
        return im
    asc = font.getmetrics()[0]
    if m.get("arc"):
        arc = m["arc"]
        Hc = (y1 - y0)
        cx, cy = (x0 + arc["cx"]) * k, (y0 + Hc - arc["cy"]) * k     # y вниз
        up = arc["up"]
        rb = max(1.0, arc["r"] * k - up * 0.36 * size)
        s = 1.0 if arc["t1"] >= arc["t0"] else -1.0
        txt = p["lines"][0]
        total = sum(font.getlength(ch) * h0 for ch in txt)
        tm = (arc["t0"] + arc["t1"]) / 2.0
        cur = tm - s * (total / 2.0) / rb
        for ch in txt:
            a = font.getlength(ch) * h0
            th = cur + s * (a / 2.0) / rb
            px, py = cx + rb * math.cos(th), cy - rb * math.sin(th)
            phi = math.degrees(math.atan2(s * math.cos(th), -s * math.sin(th)))
            # Буква — на квадратном слое, середина её БАЗОВОЙ линии — в центре
            # слоя: поворот вокруг центра ставит базовую линию на дугу.
            side = int(size * 3) + 2
            sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
            ImageDraw.Draw(sq).text((side / 2.0 - a / 2.0, side / 2.0 - asc), ch, font=font, fill=ink)
            sq = sq.rotate(phi, resample=Image.BICUBIC)
            _put(big, sq, (px - side / 2.0, py - side / 2.0))
            cur += s * a / rb
        return
    if m["angle"]:
        g = layer(p["lines"][0])
        gr = g.rotate(m["angle"], expand=True, resample=Image.BICUBIC)
        cx, cy = (x0 + x1) / 2.0 * k, (y0 + y1) / 2.0 * k
        _put(big, gr, (cx - gr.size[0] / 2.0, cy - gr.size[1] / 2.0))
        return
    parts = p.get("parts") or [{"top": 0, "bot": (y1 - y0) * k, "lines": p["lines"],
                                "size": size, "step": step, "font": font}]
    for part in parts:
        font, size, step = part["font"], part["size"], part["step"]
        asc = font.getmetrics()[0]
        if "bases" in part:
            # Строка — на своей базовой линии (Ф1); первая строка КАЖДОГО
            # абзаца — с отступом (Х3), у письма справа налево — справа (Х4);
            # по ширине — все строки абзаца, кроме последней (Х2).
            heads = set(part.get("heads") or [0])
            nl = len(part["lines"])
            for n_, ln in enumerate(part["lines"]):
                ind = part["indent"] if n_ in heads else 0.0
                y_ = y0 * k + part["bases"][n_] - asc - sw
                last = n_ == nl - 1 or (n_ + 1) in heads
                if part.get("justify") and not last and _put_justified(
                        big, layer, ln, font, h0, x0 * k + part["x0"] + (0 if part.get("rtl") else ind),
                        x0 * k + part["x1"] - (ind if part.get("rtl") else 0), y_, sw, part.get("rtl")):
                    continue
                g = layer(ln, font, size)
                if p["align"] == "center":
                    x = x0 * k + (part["x0"] + part["x1"]) / 2.0 - g.size[0] / 2.0
                elif p["align"] == "right" or (part.get("justify") and part.get("rtl")):
                    x = x0 * k + part["x1"] - g.size[0] - (ind if part.get("rtl") else 0.0)
                else:
                    x = x0 * k + part["x0"] + ind
                _put(big, g, (x - sw, y_))
            continue
        top, bot = y0 * k + part["top"], y0 * k + part["bot"]
        block_h = (len(part["lines"]) - 1) * step + size * 0.95
        y = top + max(0.0, ((bot - top) - block_h) / 2.0) - (asc - 0.74 * size)
        for ln in part["lines"]:
            g = layer(ln, font, size)
            if p["align"] == "center":
                x = (x0 + x1) / 2.0 * k - g.size[0] / 2.0
            elif p["align"] == "right":
                x = x1 * k - g.size[0]
            else:
                x = x0 * k
            _put(big, g, (x - sw, y - sw))
            y += step


_DASH_CACHE: dict = {}


def _short_hyphen(path: str) -> bool:
    """Х7: дефис шрифта короче 0.25 кегля, а тире в нём есть и не длиннее
    0.45 кегля — при печати дефис заменяется тире (у Marck Script дефис —
    косая черточка в 0.2 кегля, и «free-living» читалось «freeliving»)."""
    if path not in _DASH_CACHE:
        ok = False
        try:
            f = ImageFont.truetype(path, 100)
            ok = (f.getlength("-") < 25 and _font_covers(path, "\u2013")
                  and f.getlength("\u2013") <= 45)
        except Exception:
            ok = False
        _DASH_CACHE[path] = ok
    return _DASH_CACHE[path]


# Х2: выключка по ширине — промежутки между словами растягиваются; шире
# `IMG_JUSTIFY_MAX` обычного пробела — строка остаётся невыключенной
# (дыры в строке хуже рваного края). Письмо без пробелов — не растягиваем.
IMG_JUSTIFY_MAX = float(os.environ.get("IMG_JUSTIFY_MAX", "3"))


def _put_justified(big, layer, ln: str, font, h0: float, xa: float, xb: float, y: float,
                   sw: int, rtl: bool) -> bool:
    words = ln.split(" ")
    if len(words) < 2:
        return False
    ims = [layer(w_) for w_ in words]
    total = sum(im.size[0] - 2 for im in ims)
    gap = ((xb - xa) - total) / (len(words) - 1)
    space = font.getlength(" ") * h0
    if gap <= 0 or gap > IMG_JUSTIFY_MAX * max(1.0, space):
        return False
    if rtl:
        x = xb
        for im in ims:
            x -= im.size[0] - 2
            _put(big, im, (x - sw, y))
            x -= gap
    else:
        x = xa
        for im in ims:
            _put(big, im, (x - sw, y))
            x += im.size[0] - 2 + gap
    return True


def _cut_patch(arr, pm: dict, others: list, w: int, h: int) -> Optional[dict]:
    """Х8: буква, разрезанная краем вырезки (буквица выше рамки блока), —
    стирается целиком. Заплатка шире вырезки или None — продолжать нечего."""
    tp = _tp()
    if tp is None:
        return None
    seed = pm["alpha"] > 0
    x0, y0, x1, y1 = pm["pbox"]
    sides = tp.cut_sides(seed)
    sides = (sides[0] and x0 > 0, sides[1] and y0 > 0, sides[2] and x1 < w, sides[3] and y1 < h)
    if not any(sides):
        return None
    it = pm["it"]
    lh = float(it.get("lineH") or 0) or float((pm.get("geo") or {}).get("pitch") or 0) or pm["em"] / pm["k"]
    R = int(round(tp.CUT_REACH * lh))
    ex = _clip((x0 - (R if sides[0] else 0), y0 - (R if sides[1] else 0),
                x1 + (R if sides[2] else 0), y1 + (R if sides[3] else 0)), w, h)
    rgb = _np.ascontiguousarray(_visible(arr[ex[1]:ex[3], ex[0]:ex[2]])[..., :3].astype(_np.uint8))
    sd = _np.zeros(rgb.shape[:2], bool)
    sd[y0 - ex[1]:y1 - ex[1], x0 - ex[0]:x1 - ex[0]] = seed
    inner = (x0 - ex[0], y0 - ex[1], x1 - ex[0], y1 - ex[1])
    foreign = [(o[0] - ex[0], o[1] - ex[1], o[2] - ex[0], o[3] - ex[1]) for o in others]
    add = tp.continuation_mask(rgb, sd, inner, lh, foreign)
    if add is None:
        return None
    mask = sd | add
    m2 = {"erase_mask": mask, "mask": mask, "flat": False, "pitch": lh, "em": 0.8 * lh,
          "bg": tuple(int(v) for v in _np.median(rgb[~mask], axis=0))}
    try:
        er, al = tp.erase(rgb, m2)
    except Exception:
        return None
    return {"box": ex, "erased": er, "alpha": al}


def _refuse(items: list, why: str) -> tuple:
    return None, [{"i": i, "ok": False, "why": why} for i in range(len(items))]


# Ф5. Плашка (буквы по пикселям не выделились) на НЕРОВНОМ фоне — не
# сплошной прямоугольник. Симптом (проект 89): абзац конспекта лёг под серый
# прямоугольник 680×590 — темнее бумаги, без клетки и без светового
# перепада фото; цвет — мода по всей рамке вместе с линиями и сглаживанием
# букв. Правило: на неровном фоне плашка — фон, восстановленный медианой
# с окном шире буквы по уменьшенной копии (снимает буквы и тонкие линии,
# оставляет перепад света); ровный фон — как прежде, сплошным цветом.
# Рамка плашки — по рамкам строк с полем `IMG_PLATE_PAD` строки, а не по
# раздутой рамке блока.
IMG_PLATE_PAD = float(os.environ.get("IMG_PLATE_PAD", "0.3"))


def _plate_bg(arr, box, lh: float, k: int):
    """Восстановленный фон под плашку (картинка Pillow размера box × k)
    или None — нечем."""
    tp = _tp()
    if tp is None:
        return None
    import cv2
    x0, y0, x1, y1 = box
    reg = _np.ascontiguousarray(_visible(arr[y0:y1, x0:x1])[..., :3].astype(_np.uint8))
    if reg.size == 0:
        return None
    s = max(1.0, (lh or 20.0) / 12.0)
    small = cv2.resize(reg, (max(1, int(reg.shape[1] / s)), max(1, int(reg.shape[0] / s))),
                       interpolation=cv2.INTER_AREA)
    kk = tp._odd(1.6 * (lh or 20.0) / s, 3, 99)
    bg = cv2.medianBlur(small, kk) if min(small.shape[:2]) > kk else small
    bg = cv2.resize(bg, ((x1 - x0) * k, (y1 - y0) * k), interpolation=cv2.INTER_LINEAR)
    return Image.fromarray(bg)


def render_target(img_bytes: bytes, items: list, obstacles: Optional[list] = None) -> tuple:
    """Стереть исходные надписи и написать перевод. (новые байты | None, отчёт).

    Отчёт по каждому блоку обязателен: перерисовать удаётся не всё, а молча
    пропущенный блок остаётся на языке оригинала — человек узнает об этом,
    только открыв готовый файл.

    Три прохода: замер всех блоков; страница (Ф4 — один кегль, шаг и цвет
    у абзацев одного класса); раскладка и печать. `obstacles` — рамки ВСЕХ
    надписей картинки (и непереведённых): длинный перевод уходит в свободные
    строки ниже только мимо них (Ф3)."""
    if Image is None or _np is None:
        return _refuse(items, "no_pillow")
    if not items:
        return None, []
    fpath = font_path()
    if fpath is None:
        return _refuse(items, "no_font")
    try:
        im = _open(img_bytes)
        # Непомерная картинка прилетит сюда `TooBig`, и её текст уйдёт
        # в причину отказа `open:…` — по каждому блоку, как и положено.
        fmt = (im.format or "").upper()
        info = dict(im.info or {})
        orig_mode = im.mode
        if fmt not in _SAVE:
            return _refuse(items, "format:" + (fmt or "?"))
        if fmt == "GIF" and (getattr(im, "n_frames", 1) > 1 or "transparency" in info):
            # Анимация схлопнулась бы в один кадр, а прозрачность стала бы
            # чёрным прямоугольником посреди страницы. Такой текст уходит
            # подписью — это честнее испорченной картинки.
            return _refuse(items, "format:GIF-special")
        alpha = _has_alpha(im)
        im = im.convert("RGBA" if alpha else "RGB")
    except Exception as e:
        return _refuse(items, "open:%s" % e)

    w, h = im.size
    arr = _np.asarray(im)
    k = _scale_for(im, items)
    # Х10: эпоха — свойство страницы: заголовок без ъ и ѣ («СМЕРТЬ
    # ЧИНОВНИКА.») набран той же старой антиквой, что и текст под ним.
    if any(_pf().pre_reform(x.get("src") or "") for x in items):
        items = [dict(x, era="old") for x in items]
    big = im.resize((w * k, h * k), Image.LANCZOS) if k > 1 else im.copy()
    draw = ImageDraw.Draw(big)
    n = len(items)
    report: list = [None] * n
    plan, paint = [], []
    # ── Проход 1: проверки рамки и замер по пикселям ──
    pre: list = [None] * n
    pms: list = [None] * n
    for i, it in enumerate(items):
        text = (it.get("text") or "").strip()
        box = it.get("box") or [0, 0, 0, 0]
        if not text:
            report[i] = {"i": i, "ok": False, "why": "empty"}
            continue
        bw0, bh0 = box[2] - box[0], box[3] - box[1]
        vertical = bw0 > 0 and (it.get("rows") or 1) <= 1 and bh0 >= bw0 * IMG_VERT_RATIO
        pad_y = _pad_for(box, it.get("lineH"), it.get("rows"), 0.14)
        pad_x = _pad_for(box, it.get("lineH"), it.get("rows"), 0.10)
        want = (box[0] - pad_x, box[1] - pad_y, box[2] + pad_x, box[3] + pad_y)
        pbox = _clip(want, w, h)
        want_area = max(1, (want[2] - want[0]) * (want[3] - want[1]))
        if (pbox[2] - pbox[0]) * (pbox[3] - pbox[1]) < IMG_BOX_KEEP * want_area:
            # Рамка не помещается в картинку: координаты посчитаны не для неё.
            # `_clip` прижал бы их к краю, и перевод встал бы в угол.
            report[i] = {"i": i, "ok": False, "why": "outside"}
            continue
        if pbox[2] - pbox[0] < 4 or pbox[3] - pbox[1] < 4:
            report[i] = {"i": i, "ok": False, "why": "tiny_box"}
            continue
        if vertical and _tp() is None:
            # Надпись оригинала шла сверху вниз (`IMG_VERT_RATIO`), а мерить
            # её угол нечем — подпись.
            report[i] = {"i": i, "ok": False, "why": "vertical"}
            continue
        pre[i] = (pbox, vertical, text)
        # Сперва — замер по пикселям и стирание (`text_paint`): цвет, кегль,
        # жирность, угол и дуга как у оригинала, а неровный фон стирается
        # по маске букв (клетка и линейка — по модели бумаги, Ф6).
        pms[i] = _paint_measure(arr, pbox, it, k, draw)

    # ── Проход 2: страница — один кегль, шаг и цвет у класса абзацев (Ф4) ──
    boxes_all = [list(o) for o in (obstacles or []) if o and len(o) >= 4]
    for j, it2 in enumerate(items):
        if it2.get("box"):
            boxes_all.append(list(it2["box"]))

    def others_of(i):
        own = list(items[i].get("box") or [])[:4]
        return [o for o in boxes_all if o[:4] != own]
    even = _page_even(pms, draw, arr, w, h, others_of)

    # ── Проход 3: раскладка, плашка там, где букв не выделить ──
    for i, it in enumerate(items):
        if report[i] is not None or pre[i] is None:
            continue
        pbox, vertical, text = pre[i]
        box = it.get("box") or [0, 0, 0, 0]
        pm = pms[i]
        pp = None
        if pm is not None:
            pp = even.get(i)
            if pp is None:
                extra = _free_rows(pm, others_of(i), arr, w, h) if pm.get("geo") else 0
                pp = _paint_layout(pm, draw, extra=extra)
        if pp is not None and vertical and abs(abs(pp["m"]["angle"]) - 90) > 20 \
                and not pp["m"].get("arc"):
            # Детектор сказал «одна строка, рамка выше ширины», а буквы в ней
            # горизонтальные: где и под каким углом текст — неизвестно, и
            # писать наугад нельзя.
            report[i] = {"i": i, "ok": False, "why": "vertical"}
            continue
        if pp is not None:
            pp["i"] = i
            pp["patch"] = _cut_patch(arr, pm, others_of(i), w, h)
            paint.append(pp)
            r = {"i": i, "ok": True, "size": round(float(pp["size"]) / k, 1),
                 "rows": len(pp["lines"]), "paint": 1}
            if pp.get("over"):
                r["over"] = 1           # строк больше, чем места: сказано числом
            if i in even:
                r["even"] = 1
            if pm.get("fam"):
                r["fam"] = pm["fam"]    # чем напечатано: рукопись, машинопись, засечки
            if pm.get("handFallback"):
                r["handFallback"] = 1   # рукописного файла с этими буквами нет
            if pm["m"].get("eraseHow"):
                r["erase"] = pm["m"]["eraseHow"]
            report[i] = r
            continue
        if vertical:
            report[i] = {"i": i, "ok": False, "why": "vertical"}
            continue
        flat = flatness(arr, pbox)
        if flat < IMG_FLAT_MIN and _tp() is None:
            # Пёстрый фон и мерить буквы нечем: заливка была бы заплаткой.
            report[i] = {"i": i, "ok": False, "why": "flat", "flat": round(flat, 3)}
            continue
        # Пёстрый фон, букв по пикселям не выделить: перевод — на плашке
        # цвета фона В САМОЙ картинке, а не подписью под ней (подписи под
        # рисунками читатель не просил; решение владельца 11.10.2026).
        lbs = [lb for lb in (it.get("lineBoxes") or []) if lb and len(lb) >= 4]
        if lbs and int(it.get("rows") or 1) == len(lbs):
            # Рамка плашки — по строкам с небольшим полем (Ф5), не шире рамки.
            lh = float(it.get("lineH") or 0) or (box[3] - box[1]) / max(1, len(lbs))
            pd = IMG_PLATE_PAD * lh
            pbox = _clip((min(b[0] for b in lbs) - pd, min(b[1] for b in lbs) - pd,
                          max(b[2] for b in lbs) + pd, max(b[3] for b in lbs) + pd), w, h)
            pbox = (max(pbox[0], pre[i][0][0]), max(pbox[1], pre[i][0][1]),
                    min(pbox[2], pre[i][0][2]), min(pbox[3], pre[i][0][3]))
        fill, ink = _fill_and_ink(arr, pbox)
        sbox = [v * k for v in pbox]
        bw, bh = sbox[2] - sbox[0], sbox[3] - sbox[1]
        font, rows, step, size = _fit(draw, text, _paint_font(False, text, it.get("fam") or "") or fpath,
                                      bw, bh, max(6, int(bh)))
        if font is None or size < IMG_FONT_MIN_PX * k:
            # Влезть-то влезет, но читать будет нечего. Такой блок уходит
            # подписью под картинкой — это честнее нечитаемой строки.
            report[i] = {"i": i, "ok": False, "why": "tiny_font", "size": round(size / k, 1)}
            continue
        bgimg = None
        if flat < IMG_FLAT_MIN and arr.ndim == 3 and arr.shape[-1] == 3:
            # Прозрачная картинка — прежней заливкой: она хранит прозрачность.
            bgimg = _plate_bg(arr, pbox, float(it.get("lineH") or 0), k)
        plan.append({"i": i, "sbox": sbox, "font": font, "rows": rows, "step": step,
                     "fill": fill, "ink": ink, "bg": bgimg,
                     "align": _start_align(it.get("align"), it.get("text"))})
        report[i] = {"i": i, "ok": True, "size": round(size / k, 1), "rows": len(rows)}
    report = [r for r in report if r is not None]
    if not plan and not paint:
        return None, report

    for p in paint:
        x0, y0, x1, y1 = p["pbox"]
        er = Image.fromarray(p["erased"]).convert(big.mode if big.mode in ("RGB", "RGBA") else "RGB")
        al = Image.fromarray(p["alpha"])
        if k > 1:
            er = er.resize(((x1 - x0) * k, (y1 - y0) * k), Image.LANCZOS)
            al = al.resize(((x1 - x0) * k, (y1 - y0) * k), Image.LANCZOS)
        if er.mode == "RGBA":
            er.putalpha(255)
        big.paste(er, (x0 * k, y0 * k), al)
    # Заплатка буквы, разрезанной краем вырезки (Х8), — ПОСЛЕ стирания
    # блока: она стирает букву целиком одним проходом, и шва по краю
    # вырезки нет.
    for p in paint:
        pt_ = p.get("patch")
        if not pt_:
            continue
        ex = pt_["box"]
        er = Image.fromarray(pt_["erased"]).convert(big.mode if big.mode in ("RGB", "RGBA") else "RGB")
        al = Image.fromarray(pt_["alpha"])
        if k > 1:
            er = er.resize(((ex[2] - ex[0]) * k, (ex[3] - ex[1]) * k), Image.LANCZOS)
            al = al.resize(((ex[2] - ex[0]) * k, (ex[3] - ex[1]) * k), Image.LANCZOS)
        if er.mode == "RGBA":
            er.putalpha(255)
        big.paste(er, (ex[0] * k, ex[1] * k), al)
    # Сперва ВСЕ заливки, потом ВСЕ надписи. Рамки соседних блоков законно
    # пересекаются, и заливка второго стирала бы уже написанный перевод
    # первого — с отчётом «оба написаны».
    for p in plan:
        if p.get("bg") is not None:
            bg = p["bg"].convert(big.mode) if big.mode in ("RGB", "RGBA") else p["bg"]
            big.paste(bg, (int(p["sbox"][0]), int(p["sbox"][1])))
        else:
            draw.rectangle(p["sbox"], fill=p["fill"])
    for p in plan:
        sbox, bw = p["sbox"], p["sbox"][2] - p["sbox"][0]
        ink = p["ink"] + (255,) if big.mode == "RGBA" else p["ink"]
        y = sbox[1] + max(0, ((sbox[3] - sbox[1]) - p["step"] * len(p["rows"])) / 2)
        for row in p["rows"]:
            x = sbox[0]
            if p["align"] in ("center", "right"):
                free = max(0, bw - draw.textlength(row, font=p["font"]))
                x = sbox[0] + (free / 2 if p["align"] == "center" else free)
            draw.text((x, y), row, font=p["font"], fill=ink)
            y += p["step"]
    for p in paint:
        _paint_put(big, p)
    try:
        return _save(big, fmt, info, orig_mode), report
    except Exception as e:
        # Отчёт не должен пропасть вместе со сборкой: без него вызывающий
        # не узнает, что перерисовки не было, и не поставит подписи.
        print("[image_text] картинка не сохранилась: %s" % e, file=sys.stderr)
        return None, [{**r, "ok": False, "why": r.get("why") or "save:%s" % e}
                      for r in report]
