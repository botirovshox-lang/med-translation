# -*- coding: utf-8 -*-
"""Приглашения: кто привёл клиента, тот получает страницы.

Зачем отдельный модуль, а не двадцать строк в `main.py`: здесь считаются
ДЕНЬГИ, и правила этого счёта расходятся с правилами всего остального.
Собраны они в одном месте, чтобы их было видно целиком — и чтобы мимо них
нельзя было пройти, добавляя третью дверь к страницам.

Законы, которые нельзя ослаблять:

1. **Ссылка — это МЕТКА ПРОИСХОЖДЕНИЯ, а не дверь.** Она не входит,
   не заводит учётную запись и не даёт доступа ни к чему: человек по ней
   попадает на обычную форму регистрации, где вводит почту, пароль
   и согласие с офертой. Это тот же закон, по которому у приглашения
   в команду НЕТ ссылки из письма (`_mail_invite`): ссылка, дающая права,
   была бы вторым входом мимо пароля.

2. **Начисление — по ПОДТВЕРЖДЁННОЙ почте, а не по факту регистрации.**
   `POST /api/auth/register` заводит организацию ДО того, как человек
   прочитал письмо, и `emailVerified` гейтит только вход. Начисляй мы
   в `register` — страницы раздавались бы за POST с любым синтаксически
   верным адресом, которого никто не открывал: пять регистраций в час
   с одного IP (`SIGNUP_MAX_PER_HOUR`), сколько угодно с VPN. Поэтому
   крючок стоит в `verify_email`, и это единственная точка, где почта
   доказана.

3. **Процент берётся с ВЫСШЕЙ ТОЧКИ, а не с суммы пополнения.** Поле
   `refPaid` хранит ту базу, с которой процент УЖЕ взят, и начисляется
   `percent × max(0, pagesCredit − refPaid)`. Разница не косметическая:
   «+100 / −100 / +100» по сумме пополнений дало бы процент ДВАЖДЫ за одни
   и те же сто страниц, а по высшей точке — ровно один раз. Тот же приём,
   что у `imagePagesBooked` и `handPagesBooked`: вниз счётчик не идёт,
   исправление минусом уже начисленного не отнимает.

4. **Стартовый лимит из окружения процентом НЕ оплачивается.** Первое
   пополнение новой организации поднимает `pagesCredit` от `TENANT_MAX_PAGES`
   (строка `env` в журнале) — это не оплата, а умолчание сервиса. Поэтому
   `refPaid` у приглашённого начинается ОТ этого числа: иначе при лимите
   200 и проценте 10 первое же админское «+1» подарило бы пригласившему
   двадцать страниц.

5. **КОМАНДА рефералом не считается.** `POST /api/teams` — вторая фабрика
   арендаторов в системе, и там нет ни почты, ни проверки: пять команд
   на человека (`TEAM_MAX_PER_USER`) превратились бы в ферму из одной
   учётной записи, без второй почты вообще. Признак — `tenant["team"]`.

6. **Начисление не роняет то, ради чего человек пришёл.** Регистрация,
   не состоявшаяся из-за бонуса, обошлась бы дороже любого бонуса,
   поэтому расчёт обёрнут целиком, а сбой — строка в журнал.

7. **Все нули по умолчанию.** Платёжного шлюза в системе нет, и «оплата» —
   это пополнение страниц суперпользователем руками. Значит единственный
   настоящий рубеж против фермы — тот, что кто-то ДОЛЖЕН нажать «Пополнить».
   Пока владелец сервиса не назначил числа, программа не раздаёт ничего.
"""

import re
import secrets

KEY = "referral"                  # верхний ключ STATE (в `/api/seed` белый список)

# Код в ссылке. Без похожих знаков (0/O, 1/l/I): его диктуют голосом
# и переписывают с экрана, а «не тот символ» читается как «ссылка не работает».
_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
CODE_LEN = 8
CODE_RE = re.compile(r"^[A-Z2-9]{4,16}$")


def defaults() -> dict:
    """Настройка сервиса, одна на всех. Все нули — см. закон 7."""
    return {"enabled": False,
            "signupPages": 0.0,      # страниц пригласившему за подтверждённую регистрацию
            "welcomePages": 0.0,     # страниц самому приглашённому
            "percent": 0.0,          # % от страниц, выданных приглашённому
            "maxPerInvitee": 0.0,    # потолок начисления с одного приглашённого (0 — без)
            "maxTotal": 0.0}         # потолок начисления всего на организацию (0 — без)


def settings(state) -> dict:
    """Настройка с умолчаниями. Поля дописываются к существующей записи:
    новое поле у боевых данных обязано появиться со своим умолчанием,
    а не превратить чтение в KeyError."""
    got = state.setdefault(KEY, {})
    for k, v in defaults().items():
        got.setdefault(k, v)
    return got


def enabled(state) -> bool:
    return bool(settings(state).get("enabled"))


def norm_code(raw) -> str:
    """Код из адреса — к канону. Пришёл он ИЗВНЕ, поэтому проверяется
    формой, а не доверием: по нему ищут организацию, и свободная строка
    в этом месте была бы поиском по чему угодно."""
    c = str(raw or "").strip().upper().replace("-", "")
    return c if CODE_RE.match(c) else ""


def new_code(taken) -> str:
    """Свободный код. `taken` — множество занятых: их десятки, индекс тут
    был бы структурой, которую надо чинить при удалении организации."""
    for _ in range(50):
        c = "".join(secrets.choice(_ALPHABET) for _ in range(CODE_LEN))
        if c not in taken:
            return c
    return ""                         # не нашли — пусть решает вызывающий


def award_for_topup(rec: dict, credit_now: float, percent: float) -> float:
    """Сколько страниц причитается пригласившему за ЭТО пополнение.

    Считается по высшей точке (закон 3): база, с которой процент уже взят,
    лежит в `refPaid`, и платим мы только за то, что выросло СВЕРХ неё.
    Запись `refPaid` двигает вызывающий — и только после удачного начисления.
    """
    if percent <= 0:
        return 0.0
    paid = float(rec.get("refPaid") or 0.0)
    grew = float(credit_now) - paid
    return round(grew * percent / 100.0, 3) if grew > 0 else 0.0


def cap(amount: float, rec_invitee: dict, earned_total: float, cfg: dict) -> float:
    """Обрезать начисление потолками. Ноль потолка — «без потолка»,
    и это НЕ то же самое, что ноль начисления: первое решение владельца
    сервиса, второе — арифметика."""
    per = float(cfg.get("maxPerInvitee") or 0)
    tot = float(cfg.get("maxTotal") or 0)
    if per > 0:
        left = per - float(rec_invitee.get("refPaidOut") or 0.0)
        amount = min(amount, max(0.0, left))
    if tot > 0:
        amount = min(amount, max(0.0, tot - float(earned_total or 0.0)))
    return round(max(0.0, amount), 3)
