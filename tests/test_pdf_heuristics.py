"""Чистка PDF по геометрии: правила, найденные на боевой книге после
первого выпуска разбора по месту (Лазебный, «Пчелиная аптека»).

  D. колонтитулы кластеризовались сравнением каждого с каждым: книга, где
     в полосе на каждой странице своя строка, разбиралась минуту;
  E. любая строка из 1–3 букв кеглем вдвое больше тела удалялась как
     украшение — вместе с заголовками «IV», «Яд»; буквица вставала слитно
     без словаря («В» + «начале» → «Вначале»);
  G. стр. 303→304: врезка внизу без рамки и с рваным правым краем, а номер
     страницы распознан как «зов» кеглем 15 — абзац «…Однако одно-» /
     «го курса…» рвался врезкой и «заголовком» «зов»; врезка вверху
     следующей страницы («под-» / «Важно…» / «вергается») — так же;
     лишняя черточка за переносом («межребер- -») не давала склеить слово;
  H. колонки со сдвигом базовых линий на полстроки не узнавались.
Страницы собираются прямо в виде (строки, геометрия), как их отдаёт
`pdfpages_worker.page_lines`.
"""
