_NOISE_RE = re.compile(r"^[\W\d_]+$", re.UNICODE)


def is_noise(text: str) -> bool:
    """Строка, которую незачем переводить.

    Три случая, и все три — не текст документа: слишком короткая («а», «б»),
    совсем без букв («25.03.2008», «10mm/div») и почти без букв («250MA»,
    «kV 120») — так выглядят настройки аппарата на снимке. Надпечатку целиком
    это правило не ловит и не должно: «KARIMOV SH.» отсеивает признак
    `overlay`, который ставит модель при чтении."""
    t = (text or "").strip()
    if len(t) < IMG_MIN_CHARS or _NOISE_RE.fullmatch(t):
        return True
    return sum(1 for c in t if c.isalpha()) < IMG_MIN_LETTERS


# ── Движок поиска строк ──────────────────────────────────────────────
# RapidOCR берётся ТОЛЬКО как детектор: его распознавалка идёт с моделью
# «китайский + английский» и кириллицы не знает вовсе — «сторонний тотальный
# пиопневмоторакс» она вернула как «CTOpOHHMiTOTabHbIИWONHeBMOTOpaKC».
# Боксы при этом ставит точно, и это ровно то, чего не умеет зрячая модель:
# координаты она выдумывает. Поэтому геометрия отсюда, текст — от модели.
_ENGINE = None
_ENGINE_ERR = ""
# Модели занимают сотни мегабайт. Без лока два потока подняли бы два движка —
# то же правило, что у `_queue_term` в main.py: пишешь в общее, бери лок.
_ENGINE_LOCK = threading.Lock()


_READY = None


def engine_ready() -> tuple:
    """(готов ли движок, причина отказа словами).

    Ответ кэшируется: внутри `import rapidocr_onnxruntime`, который тянет
    в процесс onnxruntime на сотни мегабайт, а спрашивают об этом на каждом
    открытии экрана экспорта — даже в проекте без исходника. Состав пакетов
    без рестарта не меняется, так что второй раз спрашивать не о чем."""
    global _READY
    if _READY is not None:
        return _READY
    if Image is None:
        _READY = (False, "не установлен Pillow")
    elif _np is None:
        _READY = (False, "не установлен numpy")
    else:
        try:
            import rapidocr_onnxruntime  # noqa: F401
            _READY = (True, "")
        except Exception as e:
            _READY = (False, "не установлен движок распознавания (rapidocr): %s" % e)
    return _READY


def _engine():
    global _ENGINE, _ENGINE_ERR
    with _ENGINE_LOCK:
        if _ENGINE is None and not _ENGINE_ERR:
            try:
                from rapidocr_onnxruntime import RapidOCR
                cfg = {}
                if IMG_DET_MODEL:
                    cfg["det_model_path"] = IMG_DET_MODEL
                if IMG_REC_MODEL:
                    cfg["rec_model_path"] = IMG_REC_MODEL
                if IMG_REC_KEYS:
                    cfg["rec_keys_path"] = IMG_REC_KEYS
                # Порог детектора конструктору НЕ отдаём: у rapidocr 1.2 он там
                # молча пропадает (проверено — `box_thresh` остаётся 0.5),
                # а действует только переданный самому вызову. Настройка,
                # которая ничего не делает, хуже её отсутствия.
                _ENGINE = RapidOCR(**cfg)
            except Exception as e:
                _ENGINE_ERR = str(e)
                print("[image_text] движок не поднялся: %s" % e, file=sys.stderr)
        return _ENGINE


def release_engine() -> None:
    """Отпустить модели детектора. onnxruntime держит сотни мегабайт, а разбор
    картинок бывает раз в жизни проекта; воркер uvicorn один, и эта память
    отнимается у самого сервиса."""
    global _ENGINE
    with _ENGINE_LOCK:
        _ENGINE = None


def _open(img_bytes: bytes):
    """Открыть картинку, отказав ДО декода, если она непомерна.

    `Image.open` читает только заголовок — размер известен раньше, чем под
    растр выделена память, и на этом стоит вся проверка. Дальше по коду
    декод идёт через `.convert(...)`, а он памяти уже не жалеет."""
    im = Image.open(io.BytesIO(img_bytes))
    w, h = im.size
    if w * h > IMG_MAX_MPX * 1e6:
        raise TooBig("картинка %dx%d — больше потолка %g Мпкс"
                     % (w, h, IMG_MAX_MPX))
    return im


def _text_of(l: dict) -> str:
    return (l.get("text") or "").strip()


def _text_same(k: dict, l: dict) -> None:
    """Одна и та же строка, увиденная дважды: берём ту версию, что длиннее.

    Весь этот текст — работа ЧТЕНИЯ, а серверный разбор на этом шаге текста
    не имеет вовсе (его читает модель уже по готовым блокам), поэтому здесь
    всё пусто и ничего не происходит. Нужно это чтению в браузере: оно
    отдаёт текст сразу по строкам, и потерять его на склейке значит потерять
    надпись — молча, с отчётом «прочитано»."""
    if len(_text_of(l)) > len(_text_of(k)):
        k["text"] = l["text"]


def _text_join(k: dict, l: dict) -> None:
    """Два КУСКА одной строки: слева направо, перенос по дефису снимается."""
    a, b = _text_of(k), _text_of(l)
    if not a or not b:
        if a or b:
            k["text"] = a or b
        return
    if k["box"][0] > l["box"][0]:
        a, b = b, a
    k["text"] = (a[:-1] + b) if a.endswith("-") and b[:1].islower() else (a + " " + b)


# Перенос по дефису, который ЧТЕНИЕ оставило внутри строки: модель склеивает
# строки блока пробелом и оставляет «экзеку- торъ», хотя промпт просит
# склеить слово. Дальше это едет в перевод дословно — 13.10.2026 на развороте
# Чехова «civil ser- vant», «look- ed», «screw- ed up». Снимаем только «буква,
# дефис, пробел, строчная буква», и не перед союзом: «двух- и трёхкомнатные»,
# «pre- and post-test» — висячий дефис, а не перенос.
_HYPHENS = "-" + chr(0x2010) + chr(0x2011) + chr(0xAD)    # дефис, неразрывный, мягкий перенос
_HYPH_GAP_RE = re.compile(r"(?<=[^\W\d_])[" + _HYPHENS + r"]\s+(?=([^\W\d_]+))", re.UNICODE)
_SUSPENDED = {"и", "или", "либо", "да", "а", "and", "or", "to", "va", "yoki", "hamda", "және", "немесе",
              "und", "oder", "et", "ou", "y", "o", "e", "ve", "ya"}


def dehyphen(text: str) -> str:
    def rep(m):
        nxt = m.group(1)
        if not nxt[:1].islower() or nxt.lower() in _SUSPENDED:
            return m.group(0)
        return ""
    return _HYPH_GAP_RE.sub(rep, text or "")


def read_clean(text: str) -> str:
    """Текст блока из ЧТЕНИЯ: перенос снят, разрывы строк — пробелы.

    Блок — один абзац (`group_blocks`), и промпт просит склеить строки,
    но модель отдаёт их через перевод строки: 13.10.2026 на развороте Чехова
    «экзеку-⏎торъ» доехал до перевода дефисом посреди китайской фразы, а
    разрывы оригинала стали жёсткими разрывами перевода."""
    t = dehyphen(text or "")
    return re.sub(r"[ \t]*\r?\n[ \t]*", " ", t).strip()


def _block_text(lines: list) -> str:
    """Текст блока — строки сверху вниз. Перенос по дефису снимается: подпись
    под рисунком разбита на «сооб-щения», и без склейки в сегмент уедет
    обрубок, по которому потом работают и перевод, и глоссарий."""
    out = ""
    for l in sorted(lines, key=lambda x: (x["box"][1], x["box"][0])):
        t = _text_of(l)
        if not t:
            continue
        if not out:
            out = t
        elif out.endswith("-") and t[:1].islower():
            out = out[:-1] + t
        else:
            out += " " + t
    return out


def _conf_best(a, b):
    """Лучшая из двух уверенностей. «Не знаю» (None) числа не перебивает."""
    vals = [v for v in (a, b) if v is not None]
    return round(max(vals), 3) if vals else None


def _conf_worst(a, b):
    """Худшая. «Не знаю» хуже любого числа: выдать за уверенность то, чего
    не мерили, значит соврать ровно там, где на число смотрит человек."""
    if a is None or b is None:
        return None
    return round(min(a, b), 3)


def _conf_all(lines: list):
    """Худшая по списку строк — по тому же правилу."""
    vals = [l.get("conf") for l in lines]
    if not vals or any(v is None for v in vals):
        return None
    return round(min(vals), 3)


def _clip(box, w: int, h: int) -> tuple:
    x0, y0, x1, y1 = [int(round(v)) for v in box]
    x0, y0 = max(0, min(x0, w)), max(0, min(y0, h))
    x1, y1 = max(x0, min(x1, w)), max(y0, min(y1, h))
    return x0, y0, x1, y1


def _visible(reg):
    """RGB, как область БУДЕТ ВЫГЛЯДЕТЬ на белой странице документа.

    Прозрачные пиксели в PNG обычно хранят чёрный цвет, и анализ по сырым
    каналам объявлял бы прозрачный фон чёрным: краска выбиралась белая,
    а перевод получался белым по прозрачному — невидимым, с отчётом
    «написано»."""
    if reg.shape[-1] == 4:
        a = reg[:, :, 3:4].astype(float) / 255.0
        return (reg[:, :, :3].astype(float) * a + 255.0 * (1.0 - a)).astype(_np.uint8)
    return reg[:, :, :3]


def flatness(arr, box) -> float:
    """Доля пикселей рамки, совпавших с самым частым цветом.

    Это и есть ответ на вопрос «можно ли стереть строку незаметно»: под
    подписью в книге фон белый и доля близка к единице, под надписью
    на рентгенограмме — градиент, и доля мала."""
    x0, y0, x1, y1 = _clip(box, arr.shape[1], arr.shape[0])
    reg = arr[y0:y1, x0:x1]
    if reg.size == 0:
        return 0.0
    q = (_visible(reg) // 32).reshape(-1, 3)
    vals, cnt = _np.unique(q, axis=0, return_counts=True)
    mode = vals[cnt.argmax()]
    return float((_np.abs(q.astype(int) - mode.astype(int)).max(axis=1) <= 1).mean())


def _bg_of(arr, box) -> Optional[list]:
    """Цвет фона строки — медиана полосок над и под рамкой. По нему строки
    РАЗНЫХ плашек схемы (белая ячейка, розовая шапка) не собираются в один
    блок (`group_blocks`)."""
    try:
        h, w = arr.shape[:2]
        x0, y0, x1, y1 = (int(v) for v in box)
        # Т14: поле — не меньше BG_PAD_MIN пикселей и срез без «-1». Прежнее
        # `max(1, 0.15·h)` с срезом `[y0-pad : y0-1]` у строки ниже 14 пикселей
        # давало ПУСТУЮ полосу, фон был None, а None в `group_blocks` значит
        # «тот же фон»: у мелкого текста инфографики (стр. 19 проекта 14 —
        # 36 строк из 105) плашки и полосы не различались вовсе.
        pad = max(BG_PAD_MIN, int(0.15 * (y1 - y0)))
        top = arr[max(0, y0 - pad):max(0, y0), max(0, x0):min(w, x1)]
        bot = arr[min(h, y1):min(h, y1 + pad), max(0, x0):min(w, x1)]
        px = _np.concatenate([top.reshape(-1, arr.shape[-1]), bot.reshape(-1, arr.shape[-1])])
        if len(px) < 4:
            return None
        return [int(v) for v in _np.median(px[:, :3], axis=0)]
    except Exception:
        return None


# Насколько (по самому далёкому каналу) могут различаться фоны строк одного
# блока: дальше — это разные плашки схемы.
IMG_BG_SAME = int(os.environ.get("IMG_BG_SAME", "40"))
BG_PAD_MIN = 3

# Т14. Разделитель между строками: тонкая сплошная линия ДРУГОГО тона
# (светлая между полосами таблицы, рамка плашки) поперёк общей ширины двух
# строк. Фон полос «High» и «Intermediate» на стр. 19 различается на 18 из
# 255 — меньше порога `IMG_BG_SAME`, а строки внутри одной полосы дают 14, —
# отличает полосы только белая линия в 1–2 пикселя между ними.
DIV_DELTA = int(os.environ.get("IMG_DIV_DELTA", "14"))
DIV_SHARE = 0.7


def divider_between(arr, a, b) -> bool:
    """Есть ли между строкой `a` (выше) и строкой `b` строка пикселей
    сплошного тона, отличного от фона ОБЕИХ (на 14+ из 255) поперёк ВНУТРЕННИХ
    80% их общей ширины. Рамки — [x0, y0, x1, y1] в пикселях. Нет общей
    ширины, нет numpy, любой сбой — False («разделителя не нашли»)."""
    try:
        h, w = arr.shape[:2]
        xl, xr = max(a[0], b[0]), min(a[2], b[2])
        if xr - xl < 6:
            return False
        m = int(0.1 * (xr - xl))
        xl, xr = max(0, xl + m), min(w, xr - m)
        y0 = max(0, min(a[3], b[1]) - 1)
        y1 = min(h, max(a[3], b[1]) + 2)
        if y1 <= y0 or xr <= xl:
            return False

        def med(y):
            return _np.median(arr[max(0, min(h - 1, y)), xl:xr].astype(int), axis=0)
        up, dn = med(a[3] - 1), med(b[1] + 1)
        best = 0
        for y in range(y0, y1):
            row = arr[y, xl:xr].astype(int)
            mrow = _np.median(row, axis=0)
            if float(_np.mean(_np.abs(row - mrow).max(axis=1) <= 10)) < DIV_SHARE:
                continue
            d2 = min(float(_np.abs(mrow - up).max()), float(_np.abs(mrow - dn).max()))
            best = max(best, d2)
        return best >= DIV_DELTA
    except Exception:
        return False


def regroup_boxes(boxes: list, arr=None) -> list:
    """Рамки строк → группы-блоки теми же условиями, что `group_blocks`
    (колонка, кегль, выравнивание, зазор), плюс фон и разделитель между
    строками, когда есть картинка `arr`. Для строк, оставшихся от блока
    после сверки со слоем (`main._split_uncovered`): прежде подряд идущие
    непокрытые строки шли одним блоком, и три плашки рядом («Consider
    medication…» | «Consider metabolic surgery» | «When choosing…», стр. 19)
    переводились одним абзацем. Т14."""
    blocks: list = []
    for ln in sorted((list(b) for b in boxes), key=lambda b: (b[1], b[0])):
        x0, y0, x1, y1 = ln
        h = max(1, y1 - y0)
        placed = False
        for b in blocks:
            bx0, by0, bx1, by1 = b["box"]
            over = min(x1, bx1) - max(x0, bx0)
            narrow = max(1, min(x1 - x0, bx1 - bx0))
            same_size = 0.6 <= h / max(1, b["lineH"]) <= 1.7
            gap = y0 - by1
            tol = max(4.0, max(h, b["lineH"]))
            aligned = (abs(x0 - bx0) <= tol or abs(x1 - bx1) <= tol
                       or abs((x0 + x1) / 2 - (bx0 + bx1) / 2) <= tol)
            if not (over > 0.35 * narrow and same_size and aligned
                    and -0.4 * h <= gap <= 1.0 * max(h, b["lineH"])):
                continue
            if arr is not None:
                last = b["lines"][-1]
                bg = (_bg_of(arr, last), _bg_of(arr, ln))
                if (bg[0] is not None and bg[1] is not None
                        and max(abs(p_ - q_) for p_, q_ in zip(bg[0], bg[1])) > IMG_BG_SAME):
                    continue
                if divider_between(arr, last, ln):
                    continue
            b["box"] = [min(bx0, x0), min(by0, y0), max(bx1, x1), max(by1, y1)]
            b["lines"].append(ln)
            b["lineH"] = (b["lineH"] * (len(b["lines"]) - 1) + h) / len(b["lines"])
            placed = True
            break
        if not placed:
            blocks.append({"box": [x0, y0, x1, y1], "lines": [ln], "lineH": h})
    return [b["lines"] for b in blocks]


def detect_lines(img_bytes: bytes) -> Optional[list]:
    """[{box, conf, flat}] или None, если посмотреть не удалось.

    None — это «не знаю»: движка нет либо картинка не читается (битый файл,
    векторный метафайл, незнакомый формат). Пустой список означал бы «надписей
    нет», а такое утверждение делать не из чего."""
    ok, _why = engine_ready()
    if not ok:
        return None
    eng = _engine()
    if eng is None:
        return None
    try:
        im = _open(img_bytes)
        arr = _np.asarray(im.convert("RGB"))
    except TooBig as e:
        # Отдельной веткой: «непомерная» и «битая» — разные причины, и в
        # журнале их надо различать, иначе потолок не с чем сверить.
        print("[image_text] картинка не смотрится: %s" % e, file=sys.stderr)
        return None
    except Exception as e:
        print("[image_text] картинка не читается: %s" % e, file=sys.stderr)
        return None
    # Смотрим ДВАЖДЫ: как есть и увеличенной. Увеличение находит то, что
    # детектор проглядел в мелком масштабе, но само по себе не бесплатно —
    # у пограничных рамок падает уверенность, и они уходят под порог: на
    # боевой image100.png две рамки с 0.62 и 0.64 пропали совсем. Значит
    # заменять один взгляд другим нельзя, можно только сложить: найденное
    # прежним разбором обязано остаться найденным.
    try:
        found = _detect_boxes(eng, arr, 1)
    except EngineAnswer as e:
        print("[image_text] %s" % e, file=sys.stderr)
        return None
    k = _detect_scale(im.width, im.height)
    if k > 1:
        try:
            big = _np.asarray(im.convert("RGB").resize(
                (im.width * k, im.height * k), Image.LANCZOS))
            found += _detect_boxes(eng, big, k)
        except Exception as e:
            # Не нашлось памяти или картинка с сюрпризом — остаётся первый
            # взгляд. Меньше найденных строк лучше, чем разбор, упавший целиком.
            print("[image_text] увеличить не вышло (%s), смотрим как есть" % e,
                  file=sys.stderr)
    # Склейка кусков идёт ДО замера плоскости: рамка склеенной строки накрывает
    # и зазор между кусками, а по этому числу решают, можно ли писать перевод
    # поверх картинки. Померив куски порознь, мы поручились бы за место,
    # которого не смотрели, — и заливка стёрла бы попавшую в зазор графику.
    out = _join_pieces(_dedupe_boxes(found))
    # Строки, пропущенные детектором в ровной колонке (рукопись), — по краске.
    for gb in rhythm_gaps(arr, [l["box"] for l in out]):
        out.append({"box": gb, "conf": None, "gap": 1})
    # Плоскость фона считаем по ИСХОДНОЙ картинке: увеличение сглаживает
    # пиксели, и снимок сошёл бы за ровный фон, на который можно писать.
    return _finish_lines(arr, out)


# Сколько строк выше смотреть в поисках соседа над строкой (Т14): строки
# отсортированы по верху, и сосед той же колонки стоит недалеко в списке.
DIV_LOOKBACK = 60


def _finish_lines(arr, out: list) -> list:
    """Общий конец разбора строк — и своего (`detect_lines`), и чужого
    (`lines_from`, чтение в браузере): плоскость, фон, порядок и разделители.
    Одна функция на оба пути — иначе блоки по чужим строкам собирались бы
    иначе, чем по своим."""
    for l in out:
        l["flat"] = round(flatness(arr, l["box"]), 3)
        bg = _bg_of(arr, l["box"])
        if bg is not None:
            l["bg"] = bg
    out.sort(key=lambda l: (l["box"][1], l["box"][0]))
    # Т14: для каждой строки — ближайшая выше (в той же колонке), от
    # которой её отделяет линия-разделитель. Окно — `DIV_LOOKBACK` строк
    # выше, а не отказ на плотной странице.
    for j, l in enumerate(out):
        x0, y0, x1, y1 = l["box"]
        h = max(1, y1 - y0)
        for i in range(j - 1, max(-1, j - 1 - DIV_LOOKBACK), -1):
            a = out[i]["box"]
            if y0 - a[3] > 1.0 * h + 4:
                continue
            if min(x1, a[2]) - max(x0, a[0]) <= 0.35 * max(1, min(x1 - x0, a[2] - a[0])):
                continue
            if a[3] > y0 + 0.4 * h:
                continue
            if divider_between(arr, a, l["box"]):
                l["divFrom"] = list(a)
            break
    return out


def lines_from(img_bytes: bytes, raw: list) -> Optional[list]:
    """Строки, найденные НЕ нами, — в том же виде, в каком их отдаёт
    `detect_lines`. (список, ширина, высота) или None.

    Нужно это чтению в браузере: там считаются рамки и текст, а всё
    остальное обязано считаться здесь и тем же кодом. Две причины, и обе
    несущие. Плоскость фона (`flat`) — решение «можно ли стереть надпись
    и написать поверх перевод»; поверить в этом чужому слову значит
    разрешить заплатку поверх рентгенограммы по слову того, кто снимка
    не видел. А склейка кусков (`_dedupe_boxes`/`_join_pieces`) измерена
    на боевых картинках, и вторая её копия в браузере разошлась бы с этой
    первой же правкой.

    Рамки приходят снаружи, поэтому каждая прижимается к картинке, а
    вырожденные выбрасываются: `_clip` молча ставит угол, и надпись,
    посчитанная для рамки 400x300, оказалась бы написана в углу 1x1."""
    ok, _why = engine_ready_pixels()
    if not ok:
        return None
    try:
        im = _open(img_bytes)
        arr = _np.asarray(im.convert("RGB"))
    except Exception as e:
        print("[image_text] картинка не читается: %s" % e, file=sys.stderr)
        return None
    h, w = arr.shape[0], arr.shape[1]
    lines = []
    for r in (raw or []):
        # Разбор ЦЕЛИКОМ в try, и `OverflowError` назван отдельно: это
        # клиентский JSON, где `Infinity` — законное число для `float()`
        # и срыв для `int()`. Одна кривая строка не вправе уронить порцию
        # из полусотни картинок.
        try:
            x0, y0, x1, y1 = _clip([float(v) for v in r["box"]], w, h)
            conf = r.get("conf")
            conf = round(float(conf), 3) if conf is not None else None
        except (KeyError, TypeError, ValueError, OverflowError):
            continue
        if x1 - x0 < 4 or y1 - y0 < 4:
            continue
        lines.append({"box": [x0, y0, x1, y1], "conf": conf, "flat": 0.0,
                      "text": str(r.get("text") or "")})
    out = _finish_lines(arr, _join_pieces(_dedupe_boxes(lines)))
    return out, w, h


def engine_ready_pixels() -> tuple:
    """Готовность к работе С ПИКСЕЛЯМИ — без движка поиска строк.

    Отдельно от `engine_ready`, потому что вопросы разные: чтению в браузере
    движок на сервере не нужен вовсе, а Pillow и numpy нужны всегда. Одна
    проверка на двоих отказывала бы серверу в приёме чужих строк из-за
    отсутствия onnxruntime, которым он не собирался пользоваться."""
    if Image is None:
        return False, "не установлен Pillow"
    if _np is None:
        return False, "не установлен numpy"
    return True, ""


def _detect_boxes(eng, arr, k: int) -> list:
    """Рамки одного прохода, ВСЕГДА в исходных пикселях: по рамке потом стирают,
    пишут и режут кроп — в увеличенных координатах она попала бы мимо."""
    kw = {}
    if IMG_BOX_THRESH:
        kw["box_thresh"] = float(IMG_BOX_THRESH)
    if IMG_DET_ONLY:
        kw.update(use_det=True, use_cls=False, use_rec=False)
    else:
        # Движок сам выбрасывает строки с уверенностью чтения ниже 0.5 — ДО нас,
        # и правила «строка внутри столбца» ниже их иначе не увидели бы. Порог
        # ноль: строку, которую распознавалка не прочла вовсе, судит геометрия
        # (`_column_rescue`), а не её уверенность.
        kw["text_score"] = 0.0
    res, _elapse = eng(arr, **kw) if kw else eng(arr)
    if IMG_DET_ONLY:
        _warn_if_read_anyway(res)
    out, weak, faint, bad = [], [], [], 0
    for item in (res or []):
        pts, score = _unpack(item)
        if pts is None:
            bad += 1
            continue
        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        box = [int(min(xs) / k), int(min(ys) / k),
               int(max(xs) / k), int(max(ys) / k)]
        if box[2] - box[0] < 4 or box[3] - box[1] < 4:
            continue
        rec = {"box": box, "conf": round(score, 3) if score is not None else None, "flat": 0.0}
        if score is not None and score < IMG_MIN_CONF:
            (weak if score >= IMG_WEAK_CONF else faint).append(rec)
            continue
        out.append(rec)
    out += [w for w in weak if _in_column(w["box"], out)]
    out += _column_rescue([w for w in weak if w not in out] + faint, out)
    # Движок ответил, а разобрать не вышло НИ ОДНОЙ записи — это смена формы
    # ответа (другая версия пакета), а не картинка без надписей. Разница
    # несущая: пустой список объявит картинку прочитанной навсегда, и платное
    # чтение к ней больше не придёт.
    if bad and not out:
        raise EngineAnswer("ответ движка не разобран: %d записей" % bad)
    return out


# Строка, которую распознавалка движка прочла неуверенно, но которая стоит
# ВНУТРИ столбца текста. Распознавалка знает китайский и английский, и чистую
# кириллицу оценивает низко: 12.10.2026 на фото музейной таблички строка
# «электронная цифровая» получила 0.43 и пропала между «два аккумулятора,» и
# «дублированная система зажигания» — её перевода не было ни на одном языке,
# а русская строка осталась посреди переведённой картинки. Порог 0.6 не
# трогаем: чтение движка — бесплатный фильтр мусора (замер в CLAUDE.md,
# «Движок ищет строки»). Мусор и обрывок рисунка в ровный столбец не встают,
# поэтому слабую строку берём, только если ПРЯМО над ней и прямо под ней
# стоят уверенные строки той же высоты и с тем же левым краем. Найденное
# прежним разбором остаётся найденным: правило только добавляет.
IMG_WEAK_CONF = float(os.environ.get("IMG_WEAK_CONF", "0.3"))


def _in_column(box: list, strong: list) -> bool:
    h = box[3] - box[1]
    if h <= 0:
        return False

    def kin(o):
        oh = o[3] - o[1]
        return abs(oh - h) <= 0.3 * h and abs(o[0] - box[0]) <= 1.5 * h

    above = below = False
    for s in strong:
        o = s["box"]
        if not kin(o):
            continue
        if 0 <= box[1] - o[3] <= 0.8 * h:
            above = True
        if 0 <= o[1] - box[3] <= 0.8 * h:
            below = True
    return above and below


# Строка, которой распознавалка движка поставила НОЛЬ, — не обязательно
# мусор. 13.10.2026 на машинописной справке 1940 г. (лендинг, «Сканы и фото»)
# три строки из десяти получили 0.0 и пустой текст: латинско-китайская
# распознавалка не узнала в выцветшей ленте ни одной буквы, и строки пропали —
# их не перевели, а на переведённой картинке они остались русскими посреди
# английского. Правило `_in_column` их не спасает: оно берёт только слабые
# (от `IMG_WEAK_CONF`) и только между ДВУМЯ уверенными, а пропавшие стояли
# подряд и последними в абзаце. Здесь признак другой — ГЕОМЕТРИЯ столбца:
# строка той же высоты, выровненная с уверенными строками по левому или
# правому краю (абзацный отступ ломает левый край, обрыв абзаца — правый),
# не короче 0.6 их ширины и вплотную к одной из них сверху или снизу. Пятно
# и обрывок рисунка такой рамки не дают. Цепочкой: спасённая строка сама
# становится соседом следующей. Только добавляет найденное.
IMG_COL_WIDTH = float(os.environ.get("IMG_COL_WIDTH", "0.6"))


def _column_rescue(cands: list, strong: list) -> list:
    got: list = []
    pool = list(strong)
    changed = True
    while changed and cands:
        changed = False
        for c in list(cands):
            box = c["box"]
            h = box[3] - box[1]
            if h <= 0:
                cands.remove(c)
                continue
            mates = [s["box"] for s in pool
                     if abs((s["box"][3] - s["box"][1]) - h) <= 0.3 * h
                     and (abs(s["box"][0] - box[0]) <= h or abs(s["box"][2] - box[2]) <= h)]
            if len(mates) < 2:
                continue
            widths = sorted(m[2] - m[0] for m in mates)
            if box[2] - box[0] < IMG_COL_WIDTH * widths[len(widths) // 2]:
                continue
            if any(0 <= box[1] - m[3] <= 0.8 * h or 0 <= m[1] - box[3] <= 0.8 * h for m in mates):
                cands.remove(c)
                got.append(c)
                pool.append(c)
                changed = True
    return got


_DET_ONLY_WARNED = False


def _warn_if_read_anyway(res) -> None:
    """Сказать вслух, если движок пропустил просьбу искать БЕЗ чтения.

    У rapidocr до 1.3 никаких `use_rec` нет вовсе: лишние слова уходят
    в `**kwargs` и тихо пропадают, а чтение идёт как шло. Наружу это
    выглядит как включённая настройка, которая не работает, — и узнать
    об этом неоткуда. Отличаем по ОТВЕТУ: пришла уверенность чтения —
    значит читали."""
    global _DET_ONLY_WARNED
    if _DET_ONLY_WARNED or not res:
        return
    _DET_ONLY_WARNED = True
    if _unpack(res[0])[1] is not None:
        print("[image_text] IMG_DET_ONLY=1, но движок всё равно читает: "
              "нужен rapidocr-onnxruntime 1.3 и новее", file=sys.stderr)


def _unpack(item):
    """(четыре угла, уверенность чтения | None) из ответа движка.

    Ответ приходит в двух видах, и это не прихоть: полный проход отдаёт
    (рамка, текст, уверенность), а поиск без чтения — голую рамку, потому
    что читать было нечего. Уверенности там нет вовсе, и подставить вместо
    неё число нельзя: по нему склеивают строки и его же показывают человеку
    в списке отсеянного."""
    try:
        if len(item) >= 3 and not isinstance(item[1], (list, tuple)):
            return item[0], float(item[2])
        if len(item) == 4 and isinstance(item[0], (list, tuple)):
            return item, None
    except (TypeError, IndexError, ValueError):
        pass
    return None, None


def _dedupe_boxes(lines: list) -> list:
    """Одна и та же строка, найденная обоими проходами, — одна строка.

    Крупная рамка побеждает: увеличенный проход дробит строку чаще мелкого,
    и кусок, целиком лежащий внутри уже взятой рамки, — это она же. Обратный
    случай тоже закрыт: если целую строку нашёл только второй проход, она
    больше по площади, берётся первой и проглатывает найденный прежде кусок."""
    out: list = []
    for l in sorted(lines, key=lambda x: -((x["box"][2] - x["box"][0])
                                           * (x["box"][3] - x["box"][1]))):
        x0, y0, x1, y1 = l["box"]
        area = max(1, (x1 - x0) * (y1 - y0))
        dup = False
        for k in out:
            kx0, ky0, kx1, ky1 = k["box"]
            over = (max(0, min(x1, kx1) - max(x0, kx0))
                    * max(0, min(y1, ky1) - max(y0, ky0)))
            if over >= IMG_DUP_COVER * area:
                # Уверенность берём лучшую: строку видели дважды.
                k["conf"] = _conf_best(k["conf"], l["conf"])
                _text_same(k, l)
                dup = True
                break
            # Проходы режут строку по-разному, и рамки расходятся не вложением,
            # а внахлёст: «до пятого слова» у одного и «с третьего» у другого.
            # Оставить обе — значит завести два сегмента с общим куском текста:
            # он будет прочитан дважды, переведён дважды и дважды написан
            # поверх картинки при выгрузке. Это одна строка, и рамка у неё одна.
            if over > 0 and _same_line(k, l):
                # Текст склеиваем ДО того, как рамка стала общей: порядок
                # кусков читается по их левым краям, а у общей рамки левый
                # край уже самый левый — и правый кусок навсегда оказывался
                # первым («исследовании с рентгенологическим»).
                _text_join(k, l)
                k["box"] = [min(kx0, x0), min(ky0, y0), max(kx1, x1), max(ky1, y1)]
                k["conf"] = _conf_worst(k["conf"], l["conf"])
                dup = True
                break
        if not dup:
            out.append(l)
    return out


def _detect_scale(w: int, h: int) -> int:
    """Во сколько раз увеличить картинку перед поиском строк."""
    if max(w, h) >= IMG_DETECT_UNDER_PX:
        return 1
    if w * h * IMG_DETECT_SCALE ** 2 > IMG_DETECT_MAX_MPX * 1e6:
        return 1
    return IMG_DETECT_SCALE


# ── Сборка строк в блоки ─────────────────────────────────────────────
# Детектор находит СТРОКИ, а переводить надо предложения. Подпись под
# рисунком 174 разбита на четыре строки с переносами («сооб-щения»,
# «воздухо-носных»); отдай их модели по отдельности — получишь четыре обрубка
# вместо фразы, а глоссарий и проверки будут работать по мусору. Поэтому
# соседние строки одной колонки собираются в блок, и сегментом становится он.


def _spread(vals: list) -> float:
    m = sum(vals) / len(vals)
    return (sum((v - m) ** 2 for v in vals) / len(vals)) ** 0.5


# Абзац из трёх строк и больше выравнивается по ДОЛЕ строк, держащих край,
# а не по разбросу всех краёв. 13.10.2026 (лендинг): выключенный по ширине
# абзац Чехова с буквицей получил «вправо» — отступ первой строки за буквицей
# раздул разброс левого края, — а машинопись с двумя абзацными отступами
# получила «по центру»; перевод встал рваным левым краем. Правило: первая
# строка не судит левый край (отступ, буквица), последняя — правый (короткая
# концовка); край «держится», если строка в пределах половины высоты строки
# от медианы. Держатся оба края — «влево»: это выключка по ширине, а рисовать
# её мы умеем только от левого края. Ничья с серединой — центр. Ни один край
# не держится на 70 % строк (надписи аппарата на снимке) — прежний замер
# разбросом, как и у блока из двух строк: там нет ни отступа, ни концовки.
def _align_para(lines: list) -> str:
    ls = sorted(lines, key=lambda l: (l["box"][1], l["box"][0]))
    hs = sorted(l["box"][3] - l["box"][1] for l in ls)
    tol = max(4.0, 0.5 * hs[len(hs) // 2])

    def hold(vals):
        med = sorted(vals)[len(vals) // 2]
        return sum(1 for v in vals if abs(v - med) <= tol) / len(vals)

    a_l = hold([l["box"][0] for l in ls[1:]])
    a_r = hold([l["box"][2] for l in ls[:-1]])
    a_m = hold([(l["box"][0] + l["box"][2]) / 2 for l in ls])
    if a_l >= 0.7 and a_r >= 0.7:
        return "left"                      # выключка по ширине
    best = max(a_l, a_r, a_m)
    if best < 0.7:
        return _align_spread(lines)        # ни один край не держится — прежний замер
    if [a_l, a_r, a_m].count(best) > 1 and not (a_m == best and a_l < best and a_r < best):
        # Ничья: у коротких строк середина держится не хуже края, и доля
        # краёв не различает. Решает прежний замер разбросом.
        return _align_spread(lines)
    if a_m == best:
        return "center"
    return "left" if a_l == best else "right"


def _align_of(lines: list) -> str:
    """Как выключены строки блока: влево, по центру или вправо.

    Подпись под рисунком часто отцентрована, а колонка чисел выключена вправо;
    написать перевод от левого края значит сдвинуть его относительно картинки.
    Смотрим, какой из трёх краёв держится ровнее остальных."""
    if len(lines) < 2:
        return "left"
    if len(lines) >= 3:
        return _align_para(lines)
    return _align_spread(lines)


def block_align(b: dict) -> str:
    """Выключка блока для РИСОВАНИЯ — по его рамкам строк, а не по записи
    в карте. Запись делается при чтении и с правилами не меняется: после
    правки `_align_of` (13.10.2026) уже прочитанные картинки иначе рисовались
    бы прежним выравниванием до нового платного чтения. Рамок нет (карты
    старше `lineBoxes`) — то, что записано."""
    lb = [x for x in (b.get("lineBoxes") or []) if isinstance(x, (list, tuple)) and len(x) >= 4]
    if len(lb) >= 2:
        return _align_of([{"box": list(x[:4])} for x in lb])
    return b.get("align") or "left"


def _align_spread(lines: list) -> str:
    lefts = _spread([l["box"][0] for l in lines])
    rights = _spread([l["box"][2] for l in lines])
    mids = _spread([(l["box"][0] + l["box"][2]) / 2 for l in lines])
    best = min(lefts, rights, mids)
    if best == lefts:
        return "left"
    return "right" if best == rights else "center"


# ── Куски одной строки ───────────────────────────────────────────────
# Детектор режет строку по широкому пробелу. В выключенном по формату абзаце
# пробелы растянуты, а в разрядке они шире буквы — и на боевой странице
# учебника (image161.png) одна строка «рентгенологическим исследовании с»
# пришла ТРЕМЯ рамками. Дальше каждый обрывок уходил в модель отдельно
# и становился отдельным сегментом: «рентгенологическим», «исследовании»,
# «ании с При этом» — три строки, которые нечего переводить и по которым
# нечего проверять.
#
# Склеивать по одному лишь расстоянию НЕЛЬЗЯ, и это не осторожность, а замер:
# на той же странице до соседней КОЛОНКИ зазор 21 пиксель, а между словами
# внутри строки — 20 и 22. Правило по ширине склеило бы текст левой колонки
# с подписью правой, то есть два разных текста в один сегмент.
#
# Колонку выдаёт не зазор, а ПОВТОР края: строки колонки начинаются (или
# кончаются) на одном x, а обрывок слова стоит сам по себе. Второй признак —
# по зазору никто не пишет: если ни одна другая строка картинки не
# перечёркивает это место, значит там межколонник, а не пробел.
# Пороги — из окружения, как и все соседние: правило подбирается на боевых
# картинках, и крутить его без выката должно быть можно.
# Известный предел: край колонки считается по ВСЕМ строкам, включая сами куски,
# поэтому абзац, разорванный на нескольких строках примерно на одном x, сам
# себе создаёт «край» и остаётся несклеенным. Отличить такое от настоящей
# колонки нечем, а ошибаться дешевле в эту сторону: несклеенная строка — лишний
# сегмент, склеенная чужая — два текста в одном переводе.
IMG_JOIN_GAP = float(os.environ.get("IMG_JOIN_GAP", "1.6"))      # предел зазора в высотах строки
IMG_JOIN_TIGHT = float(os.environ.get("IMG_JOIN_TIGHT", "0.6"))  # ближе — пробел при любых признаках
IMG_JOIN_EDGE = int(os.environ.get("IMG_JOIN_EDGE", "2"))        # столько строк на одном x — край колонки
IMG_JOIN_NEAR = float(os.environ.get("IMG_JOIN_NEAR", "3"))      # свидетель ищется в стольких межстрочиях
IMG_JOIN_VOUCH = float(os.environ.get("IMG_JOIN_VOUCH", "0.5"))  # и накрывает столько от КАЖДОГО куска


def _same_line(a: dict, b: dict) -> bool:
    """Две рамки стоят на ОДНОЙ строке: тот же кегль, тот же уровень.

    Окно по высоте шире, чем у сборки блоков (там 0.6-1.7), и это не небрежность:
    кусок строки бывает в одну букву, а у буквы без выносных элементов рамка
    вдвое ниже, чем у строки с «р» и «б». Боевая image161.png: «с» в конце
    строки — 11 пикселей против 19 у «рентгенологическим», отношение 1.73, и
    прежнее окно оставляло эту букву отдельной строкой. Уровень при этом
    сходится точь-в-точь, и держат склейку именно середина и перекрытие."""
    ah = max(1, a["box"][3] - a["box"][1])
    bh = max(1, b["box"][3] - b["box"][1])
    if not (0.5 <= ah / bh <= 2.0):
        return False
    small = min(ah, bh)
    over = min(a["box"][3], b["box"][3]) - max(a["box"][1], b["box"][1])
    mid_a = (a["box"][1] + a["box"][3]) / 2
    mid_b = (b["box"][1] + b["box"][3]) / 2
    return abs(mid_a - mid_b) <= 0.5 * small and over >= 0.5 * small


def _edge_xs(lines: list, side: int, tol: float) -> list:
    """x, на которых начинается (side=0) или кончается (side=2) не меньше
    IMG_JOIN_EDGE строк, — край колонки."""
    xs = sorted(l["box"][side] for l in lines)
    out, i = [], 0
    while i < len(xs):
        j = i
        while j + 1 < len(xs) and xs[j + 1] - xs[i] <= tol:
            j += 1
        if j - i + 1 >= IMG_JOIN_EDGE:
            out.append(sum(xs[i:j + 1]) / (j - i + 1))
        i = j + 1
    return out


def _written_across(lines: list, a: dict, b: dict, h: float) -> bool:
    """По зазору между `a` и `b` пишет кто-то ЕЩЁ — значит это пробел внутри
    строки, а не межколонник.

    Три требования к свидетелю, и каждое куплено разбором ошибки:
    1) он из ДРУГОЙ полосы — сосед по своей полосе это кусок той же разорванной
       строки, он стоит по краю зазора и о нём ничего не говорит;
    2) он РЯДОМ по вертикали (`IMG_JOIN_NEAR` межстрочий). Иначе заголовок
       страницы или подпись под рисунком объявляют пробелом любой зазор, какой
       пересекают, — по всей высоте картинки, через любую колонку;
    3) он накрывает ОБА куска, а не только сам зазор. Строка своей же колонки,
       которая чуть длиннее соседних и заходит за межколонник, иначе ручается
       за пропасть, о которой ничего не знает: «левый текст + правая подпись»
       склеивались в один сегмент."""
    ax0, ax1 = a["box"][0], a["box"][2]
    bx0, bx1 = b["box"][0], b["box"][2]
    mid = (a["box"][1] + a["box"][3]) / 2
    need_a = IMG_JOIN_VOUCH * max(1, ax1 - ax0)
    need_b = IMG_JOIN_VOUCH * max(1, bx1 - bx0)
    for l in lines:
        lm = (l["box"][1] + l["box"][3]) / 2
        far = abs(lm - mid)
        if far <= 0.5 * h or far > IMG_JOIN_NEAR * h:
            continue
        lx0, lx1 = l["box"][0], l["box"][2]
        if (min(ax1, lx1) - max(ax0, lx0) >= need_a
                and min(bx1, lx1) - max(bx0, lx0) >= need_b):
            return True
    return False


def _join_pieces(lines: list) -> list:
    """Куски одной строки — в одну строку. Правила см. выше."""
    if len(lines) < 2:
        # Копии и здесь: вызывающий вправе править полученное, а разнобой
        # «иногда те же объекты, иногда копии» однажды кусает.
        return [dict(l) for l in lines]
    hs = sorted(max(1, l["box"][3] - l["box"][1]) for l in lines)
    tol = max(4.0, 0.4 * hs[len(hs) // 2])
    lefts = _edge_xs(lines, 0, tol)
    rights = _edge_xs(lines, 2, tol)
    out: list = []
    for ln in sorted(lines, key=lambda l: (l["box"][1], l["box"][0])):
        joined = False
        for cur in out:
            if cur["box"][0] > ln["box"][0] or not _same_line(cur, ln):
                continue
            gap = ln["box"][0] - cur["box"][2]
            h = max(1, max(cur["box"][3] - cur["box"][1],
                           ln["box"][3] - ln["box"][1]))
            if not (-0.5 * h <= gap <= IMG_JOIN_GAP * h):
                continue
            lo, hi = cur["box"][2], ln["box"][0]
            # Край колонки, попавший в зазор, склейку запрещает ВСЕГДА, включая
            # тесный и отрицательный зазор: рамки детектора идут с запасом, и
            # рамка соседней колонки, налезшая на пару пикселей, склеивалась
            # безусловно — мимо найденного края.
            if any(lo - tol <= e <= hi + tol for e in lefts + rights):
                continue
            # Свидетеля спрашиваем только про широкий зазор: пробел уже
            # IMG_JOIN_TIGHT высоты межколонником не бывает.
            if gap > IMG_JOIN_TIGHT * h and not _written_across(lines, cur, ln, h):
                continue
            # Текст — ДО правки рамки: порядок кусков читается по левым
            # краям, а общая рамка этот порядок стирает.
            _text_join(cur, ln)
            cur["box"] = [min(cur["box"][0], ln["box"][0]),
                          min(cur["box"][1], ln["box"][1]),
                          max(cur["box"][2], ln["box"][2]),
                          max(cur["box"][3], ln["box"][3])]
            # Худшее из двух — как у блока: склеенная строка не может быть
            # надёжнее самого сомнительного своего куска.
            cur["conf"] = _conf_worst(cur["conf"], ln["conf"])
            cur["flat"] = min(cur["flat"], ln["flat"])
            joined = True
            break
        if not joined:
            out.append(dict(ln))
    out.sort(key=lambda l: (l["box"][1], l["box"][0]))
    return out


# Кусок строки, который детектор отдал ОТДЕЛЬНОЙ рамкой и который не встал
# ни в одну строку, — а лежит внутри чужого абзаца. 13.10.2026 на развороте
# «Пёстрых рассказов» (лендинг, «Книги») слово «одинъ» сразу за буквицей
# получило свою рамку пониже строки, стало блоком из одной строки, модель
# прочла его «ОДИНЬ», и перевод встал поверх абзаца вторым текстом: «Один»
# в английском, «奥丁» (бог Óдин) в китайском. Кроп абзаца это слово и так
# накрывает — абзац прочитан с ним вместе. Блок из одной строки, лежащий
# в многострочном блоке на `IMG_INNER_COVER` своей площади, — повтор, а не
# текст. Текст браузерного чтения такой кусок не теряет: он уходит, только
# если его нет или он уже есть в тексте абзаца.
IMG_INNER_COVER = float(os.environ.get("IMG_INNER_COVER", "0.7"))


def _drop_inner(blocks: list) -> list:
    def area(b):
        return max(1, b[2] - b[0]) * max(1, b[3] - b[1])

    def inter(a, b):
        w = min(a[2], b[2]) - max(a[0], b[0])
        h = min(a[3], b[3]) - max(a[1], b[1])
        return max(0, w) * max(0, h)

    out = []
    for b in blocks:
        if len(b["lines"]) == 1:
            own = _text_of(b["lines"][0]).lower()
            host = next((c for c in blocks if c is not b and len(c["lines"]) >= 2
                         and inter(b["box"], c["box"]) >= IMG_INNER_COVER * area(b["box"])), None)
            if host is not None and (not own or own in _block_text(host["lines"]).lower()):
                continue
        out.append(b)
    return out


# Ритм строк колонки (рукопись в клетку, текст через строку). Основное правило
# склеивает строки с зазором не больше высоты строки, а конспект пишут через
# клеточку: зазор почти равен строке, край рваный, у абзаца красная строка —
# и абзац рассыпался на блоки по строкам, каждый переводился обрывком, а часть
# обрывков оставалась русской (конспект RU→EN, 16.10.2026: 4 строки из 18).
# Склеиваем, только когда колонка ДОКАЗЫВАЕТ, что это сплошной текст: не меньше
# `IMG_RHYTHM_MIN_LINES` строк одного кегля, зазоры ровные (разброс ≤
# `IMG_RHYTHM_MAD` медианы), большинство строк длинные (не короче
# `IMG_RHYTHM_WIDE` высот строки — то есть полтора десятка знаков) — у формы, оглавления и подписей схемы строки короткие
# и неровные, и правило молчит. Склеивается зазор до медиана × `IMG_RHYTHM_SLACK`:
# пустая строка между абзацами вдвое больше и абзацы не сливает.
IMG_RHYTHM_MIN_LINES = int(os.environ.get("IMG_RHYTHM_MIN_LINES", "6"))
IMG_RHYTHM_MAD = float(os.environ.get("IMG_RHYTHM_MAD", "0.35"))
IMG_RHYTHM_WIDE = float(os.environ.get("IMG_RHYTHM_WIDE", "8"))   # × высоты строки
IMG_RHYTHM_WIDE_SHARE = float(os.environ.get("IMG_RHYTHM_WIDE_SHARE", "0.6"))
IMG_RHYTHM_SLACK = float(os.environ.get("IMG_RHYTHM_SLACK", "1.35"))
IMG_RHYTHM_GAP_MAX = float(os.environ.get("IMG_RHYTHM_GAP_MAX", "4"))   # цепочка колонки, × высоты строки
IMG_RHYTHM_SIZE = float(os.environ.get("IMG_RHYTHM_SIZE", "0.4"))          # разброс высоты строки: у хвоста без выносных букв («нах.») рамка ниже на треть


def _rhythm_merge(blocks: list) -> list:
    """Склейка блоков одной колонки с ровным ритмом строк (см. `IMG_RHYTHM_*`).
    Порядок и состав строк не меняются — только их раскладка по блокам."""
    if len(blocks) < 2:
        return blocks
    order = sorted(blocks, key=lambda b: b["box"][1])
    chains: list = []
    for b in order:
        x0, y0, x1, y1 = b["box"]
        home = None
        for ch in chains:
            # Колонка — вся цепочка, а не последний блок: короткий хвост
            # абзаца («нах.») не должен рвать её перед красной строкой.
            last = ch[-1]
            lx0 = min(c["box"][0] for c in ch)
            lx1 = max(c["box"][2] for c in ch)
            ly1 = last["box"][3]
            narrow = max(1, min(x1 - x0, lx1 - lx0))
            over = min(x1, lx1) - max(x0, lx0)
            lh = max(1.0, max(b["lineH"], last["lineH"]))
            if (over > 0.7 * narrow and 0 <= y0 - ly1 <= IMG_RHYTHM_GAP_MAX * lh
                    and abs(b["lineH"] - last["lineH"]) <= IMG_RHYTHM_SIZE * lh):
                home = ch
                break
        if home is None:
            chains.append([b])
        else:
            home.append(b)
    out = []
    for ch in chains:
        lines = sorted((l for b in ch for l in b["lines"]), key=lambda l: l["box"][1])
        if len(ch) < 2 or len(lines) < IMG_RHYTHM_MIN_LINES:
            out.extend(ch)
            continue
        # Шаг — от верха до верха строки, а не зазор между рамками: у рукописи
        # высота рамки пляшет от выносных букв, и зазор вдвое неровнее шага.
        gaps = [max(0, b_["box"][1] - a_["box"][1]) for a_, b_ in zip(lines, lines[1:])]
        gs = sorted(gaps)
        med = gs[len(gs) // 2]
        mad = sorted(abs(g - med) for g in gaps)[len(gaps) // 2]
        wide = sum(1 for l in lines if (l["box"][2] - l["box"][0])
                   >= IMG_RHYTHM_WIDE * max(1, l["box"][3] - l["box"][1]))
        if med <= 0 or mad > IMG_RHYTHM_MAD * med or wide < IMG_RHYTHM_WIDE_SHARE * len(lines):
            out.extend(ch)
            continue
        cur = ch[0]
        for b in ch[1:]:
            gap = b["box"][1] - max(l["box"][1] for l in cur["lines"])
            bgs = cur.get("bg"), b.get("bg")
            same_bg = (bgs[0] is None or bgs[1] is None
                       or max(abs(p - q) for p, q in zip(bgs[0], bgs[1])) <= IMG_BG_SAME)
            # Короткая строка заканчивает абзац (хвост, заголовок, подпись):
            # к ней следующая не приклеивается.
            last = max(cur["lines"], key=lambda l: l["box"][1])["box"]
            open_end = (last[2] - last[0]) >= IMG_RHYTHM_WIDE * max(1, last[3] - last[1])
            if gap <= med * IMG_RHYTHM_SLACK and same_bg and open_end:
                cx = cur["box"]
                cur = {"box": [min(cx[0], b["box"][0]), cx[1], max(cx[2], b["box"][2]), b["box"][3]],
                       "lines": cur["lines"] + b["lines"], "bg": cur.get("bg"),
                       "src": (cur.get("src") or []) + (b.get("src") or []),
                       "lineH": ((cur["lineH"] * len(cur["lines"]) + b["lineH"] * len(b["lines"]))
                                 / (len(cur["lines"]) + len(b["lines"])))}
            else:
                out.append(cur)
                cur = b
        out.append(cur)
    return out


# Пропущенная строка в ровном ритме колонки (конспект RU→EN, 16.10.2026):
# детектор печатного текста на рукописи не увидел три строки из восемнадцати,
# и их не было ни в одном блоке — ни в переводе, ни в выгрузке. Колонка с
# ровным шагом (`IMG_RHYTHM_*`) знает, где должна стоять строка: шаг между
# соседними строками ≈ k шагов — значит пропущено k−1 мест. Место становится
# строкой, только если в нём есть КРАСКА: пиксели темнее фона места больше
# чем на `IMG_GAP_INK_DELTA` яркости (клетка и линейка тетради светлее,
# чернила — темнее), её доля не меньше `IMG_GAP_INK_SHARE` и она тянется
# по ширине не меньше `IMG_RHYTHM_WIDE` высот строки. Пустая строка между
# абзацами краски не содержит и строкой не становится.
IMG_GAP_INK_DELTA = float(os.environ.get("IMG_GAP_INK_DELTA", "70"))
IMG_GAP_INK_SHARE = float(os.environ.get("IMG_GAP_INK_SHARE", "0.02"))
IMG_GAP_STEP = float(os.environ.get("IMG_GAP_STEP", "1.7"))      # × шага: с этого — пропуск
# Краска места обязана быть СТРОКОЙ, а не куском рисунка или таблицы: место
# не накрывает найденную строку больше чем на `IMG_GAP_OVERLAP` своей площади,
# а полосы бумаги сразу над и под местом почти чисты (краски там меньше
# `IMG_GAP_EDGE` доли от краски места) — рисунок тянется за край места.
IMG_GAP_OVERLAP = float(os.environ.get("IMG_GAP_OVERLAP", "0.2"))
IMG_GAP_EDGE = float(os.environ.get("IMG_GAP_EDGE", "0.5"))


def gap_slots(boxes: list) -> list:
    """Места, где в ровной колонке должна стоять строка, а её нет:
    [(x0, y0, x1, y1, высота строки)]. Только геометрия, картинка не нужна —
    по этому ответу решают, стоит ли вообще отрисовывать страницу."""
    if len(boxes) < IMG_RHYTHM_MIN_LINES:
        return []
    chains: list = []
    for b in sorted((list(x) for x in boxes), key=lambda b: b[1]):
        h = float(b[3] - b[1])
        home = None
        for ch in chains:
            lx0 = min(c[0] for c in ch)
            lx1 = max(c[2] for c in ch)
            last = ch[-1]
            narrow = max(1, min(b[2] - b[0], lx1 - lx0))
            lh = max(1.0, h, last[3] - last[1])
            if (min(b[2], lx1) - max(b[0], lx0) > 0.7 * narrow and b[1] >= last[3]
                    and abs(h - (last[3] - last[1])) <= IMG_RHYTHM_SIZE * lh):
                home = ch
                break
        if home is None:
            chains.append([b])
        else:
            home.append(b)
    out = []
    for ch in chains:
        if len(ch) < IMG_RHYTHM_MIN_LINES:
            continue
        steps = [b_[1] - a_[1] for a_, b_ in zip(ch, ch[1:])]
        st = sorted(steps)
        pitch = st[len(st) // 2]
        mad = sorted(abs(x - pitch) for x in steps)[len(steps) // 2]
        if pitch <= 0 or mad > IMG_RHYTHM_MAD * pitch:
            continue
        lh = sorted(c[3] - c[1] for c in ch)[len(ch) // 2]
        cx0, cx1 = min(c[0] for c in ch), max(c[2] for c in ch)
        for a_, x in zip(ch, steps):
            if x < IMG_GAP_STEP * pitch:
                continue
            for j in range(1, int(round(x / pitch))):
                y0 = a_[1] + j * pitch
                slot = (cx0, y0, cx1, y0 + lh)
                area = max(1.0, (cx1 - cx0) * lh)
                if any(max(0, min(slot[2], b[2]) - max(slot[0], b[0]))
                       * max(0, min(slot[3], b[3]) - max(slot[1], b[1])) > IMG_GAP_OVERLAP * area
                       for b in boxes):
                    continue                    # место занято найденной строкой
                out.append((cx0, y0, cx1, y0 + lh, lh))
    return out


def rhythm_gaps(arr, boxes: list) -> list:
    """Рамки строк, пропущенных детектором в ровной колонке: [[x0,y0,x1,y1]].
    Место из `gap_slots` — строка, только если в нём есть краска."""
    slots = gap_slots(boxes)
    if _np is None or arr is None or not slots:
        return []
    H, W = arr.shape[:2]
    lum = arr[..., :3].astype(_np.float32) @ _np.array([0.299, 0.587, 0.114], dtype=_np.float32)
    out = []
    for x0, y0, x1, y1, lh in slots:
        x0, y0, x1, y1 = max(0, int(x0)), max(0, int(y0)), min(W, int(x1)), min(H, int(y1))
        if y1 - y0 < 4 or x1 - x0 < 8:
            continue
        band = lum[y0:y1, x0:x1]
        bg = float(_np.median(band))
        ink = band < bg - IMG_GAP_INK_DELTA
        share = float(ink.mean())
        if share < IMG_GAP_INK_SHARE:
            continue
        e = max(2, int(0.25 * lh))
        edges = [lum[max(0, y0 - e):max(0, y0 - e // 3), x0:x1],
                 lum[min(H, y1 + e // 3):min(H, y1 + e), x0:x1]]
        if any(st.size and float((st < bg - IMG_GAP_INK_DELTA).mean()) > IMG_GAP_EDGE * share
               for st in edges):
            continue                            # краска тянется за место — рисунок, не строка
        cols = _np.where(ink.any(axis=0))[0]
        if cols.size == 0 or (cols[-1] - cols[0]) < IMG_RHYTHM_WIDE * lh:
            continue
        out.append([x0 + int(cols[0]), y0, x0 + int(cols[-1]) + 1, y1])
    return out


# Версия правил сборки блоков. Запись картинки помнит, какой версией собраны
# её блоки (`groupRule`); прежняя — значит разбор картинок перегруппирует
# их сам (`regroup_plan`, `main._regroup_rec`). 2 — ритм колонки, 3 — строки,
# пропущенные детектором в ритме (`rhythm_gaps`), оба 16.10.2026.
IMG_GROUP_RULE = 3


def regroup_plan(blocks: list) -> list:
    """Какие СОХРАНЁННЫЕ блоки картинки склеились бы по нынешним правилам:
    список групп номеров (каждая — по порядку строк, длиной от двух).

    Только склейка, и только по ритму колонки: детектор заново не зовётся
    (строки лежат в `lineBoxes`), блоки не режутся, отсеянные (`skip`)
    не участвуют. Так прочитанный текст переиспользуется склейкой, а не
    покупается вторым чтением."""
    inner = []
    for i, b in enumerate(blocks or []):
        if b.get("skip") or not b.get("box"):
            continue
        lbs = b.get("lineBoxes") or [b["box"]]
        inner.append({"box": list(b["box"]), "lineH": float(b.get("lineH") or
                                                          (b["box"][3] - b["box"][1]) / max(1, len(lbs))),
                      "lines": [{"box": list(lb)} for lb in lbs], "bg": None, "src": [i]})
    return [sorted(g["src"], key=lambda k: blocks[k]["box"][1])
            for g in _rhythm_merge(inner) if len(g.get("src") or []) > 1]


def group_blocks(lines: list) -> list:
    """Строки → блоки. Блок — это то, что человек прочитал бы как один текст:
    та же колонка, тот же кегль, строки идут подряд И ВЫРОВНЕНЫ ПО ОДНОМУ КРАЮ.

    Последнее условие не украшение. Без него заголовок во всю ширину над двумя
    колонками цеплял к себе первую строку той колонки, что оказалась выше
    на пиксель, — и разбиение менялось целиком от дрожания детектора: в один
    блок попадали заголовок, строка правой колонки и строка левой, а модель
    получала склейку трёх разных текстов.

    Перед сборкой строка собирается из своих КУСКОВ (`_join_pieces`): детектор
    режет её по широкому пробелу, и до склейки «рентгенологическим»,
    «исследовании» и «с» — три разные строки, которые ни по одному краю
    не выровнены и потому в один блок не попадут никогда. Склейка живёт
    в `detect_lines` — там есть сама картинка, и плоскость фона считается уже
    по склеенной рамке."""
    blocks: list = []
    for ln in sorted(lines, key=lambda l: (l["box"][1], l["box"][0])):
        x0, y0, x1, y1 = ln["box"]
        h = max(1, y1 - y0)
        placed = False
        for b in blocks:
            bx0, by0, bx1, by1 = b["box"]
            over = min(x1, bx1) - max(x0, bx0)          # та же колонка
            narrow = max(1, min(x1 - x0, bx1 - bx0))
            same_size = 0.6 <= (h / max(1, b["lineH"])) <= 1.7   # тот же кегль
            gap = y0 - by1                              # идут подряд
            tol = max(4.0, max(h, b["lineH"]))          # выключены по одному краю
            aligned = (abs(x0 - bx0) <= tol
                       or abs(x1 - bx1) <= tol
                       or abs((x0 + x1) / 2 - (bx0 + bx1) / 2) <= tol)
            # Тот же фон: строки белой ячейки и розовой шапки схемы — разные
            # тексты, хотя стоят вплотную и выровнены по краю.
            bgs = b.get("bg"), ln.get("bg")
            same_bg = (bgs[0] is None or bgs[1] is None
                       or max(abs(p - q) for p, q in zip(bgs[0], bgs[1])) <= IMG_BG_SAME)
            # Т14: тонкая линия-разделитель между строкой и строкой блока
            # выше (`detect_lines` → `divFrom`) — граница плашек и полос.
            cut = bool(ln.get("divFrom")) and any(l_["box"] == ln["divFrom"] for l_ in b["lines"])
            if (over > 0.35 * narrow and same_size and aligned and same_bg and not cut
                    and -0.4 * h <= gap <= 1.0 * max(h, b["lineH"])):
                b["box"] = [min(bx0, x0), min(by0, y0), max(bx1, x1), max(by1, y1)]
                b["lines"].append(ln)
                b["lineH"] = (b["lineH"] * (len(b["lines"]) - 1) + h) / len(b["lines"])
                placed = True
                break
        if not placed:
            blocks.append({"box": [x0, y0, x1, y1], "lines": [ln], "lineH": h, "bg": ln.get("bg")})
    blocks = _drop_inner(_rhythm_merge(blocks))
    out = []
    for b in blocks:
        out.append({"box": [int(v) for v in b["box"]], "rows": len(b["lines"]),
                    # Высота СТРОКИ, а не блока. По ней считаются поля рамки
                    # и кропа: посчитанные от высоты блока, они у подписи
                    # из пяти строк заезжали на снимок сверху и на соседний
                    # абзац снизу — с отчётом «написано».
                    "lineH": int(round(b["lineH"])),
                    "conf": _conf_all(b["lines"]),
                    "flat": round(min(l["flat"] for l in b["lines"]), 3),
                    "align": _align_of(b["lines"]),
                    # Рамки СТРОК блока: по ним сверка с текстовым слоем идёт
                    # построчно (`main._mark_layer_blocks`) — строка, которой
                    # в слое нет, не пропадает вместе с соседями из слоя.
                    "lineBoxes": [[int(v) for v in l["box"]] for l in
                                  sorted(b["lines"], key=lambda l: l["box"][1])]})
        # Ключ `text` появляется ТОЛЬКО когда строки его несут. Пустая строка
        # тут была бы не безобидной: разбор картинок спрашивает модель ровно
        # про те блоки, у которых ключа нет (`"text" not in b`), — поставь его
        # всегда, и серверное чтение не спросит НИ ОДНОГО блока, отчитавшись
        # «прочитано».
        if any(_text_of(l) for l in b["lines"]):
            out[-1]["text"] = _block_text(b["lines"])
    out.sort(key=lambda b: (b["box"][1], b["box"][0]))
    return out


