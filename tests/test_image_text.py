# короткий хвост «нах.». Прежнее правило резало абзац на блоки по строкам.
def para(y, n, indent=60):
    out = []
    for k in range(n):
        x0 = 40 + (indent if k == 0 else (k * 7) % 13)
        x1 = 160 if k == n - 1 else 760 - (k * 11) % 25
        out.append(line(x0, y + k * 70, x1, y + k * 70 + 30))
    return out


