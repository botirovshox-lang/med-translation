fail = []


def check(cond, label):
    print(("  OK   " if cond else "  FAIL ") + label)
    if not cond:
        fail.append(label)


BODY = ("Лечение пчелиным ядом проводят курсом, и одного курса обычно хватает, "
        "в начале курса берут одну пчелу, яд действует на сосуды и суставы, "
        "больные подвергаются ужалениям.")


def page(lines, box=(0, 0, 400, 600), rects=(), figs=()):
    """lines: [(текст, x0, y, кегль, x1)] → (строки, геометрия)."""
    return ([l[0] for l in lines],
            {"lines": [[l[1], l[2], l[3], l[4]] for l in lines], "box": list(box),
             "rects": [list(r) for r in rects], "figs": [list(f) for f in figs]})


def body_lines(n, y0=540, text=None):
    """n строк тела кеглем 10 с интерлиньяжем 12 от поля 40 до поля 340."""
    words = (text or BODY).split()
    out, k = [], 0
    for i in range(n):
        chunk = " ".join(words[(k + j) % len(words)] for j in range(7))
        k += 7
        out.append((chunk + ("." if i == n - 1 else ","), 40, y0 - 12 * i, 10, 340))
    return out


def run(pages):
    ls = [p[0] for p in pages]
    gs = [p[1] for p in pages]
    res = pdftext.clean(ls, geom=gs)
    return [it[1] for it in res["items"] if it[0] == "p"], res["report"]


def filler(num):
    return page(body_lines(20) + [(str(num), 200, 40, 10, 212)])


print("=== G. Врезка внизу без рамки, номер «зов», продолжение на следующей ===")
